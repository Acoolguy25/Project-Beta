        static bool InRound(HS_Phase phase) => phase is HS_Phase.Hiding or HS_Phase.Seeking;
        int MyId => manager != null && manager.Connection != null ? manager.Connection.ClientId : -1;
        HS_Role MyRole => roles.TryGetValue(MyId, out var r) ? r : HS_Role.None;
        HS_Role RoleOf(int clientId) => roles.TryGetValue(clientId, out var r) ? r : HS_Role.None;

        bool ShowTag(GameCharacter character) {
            // In the results a survivor's green reveal label is their name: one name each, not two.
            if (hasState && state.phase == HS_Phase.Results && IsRevealed(character.OwnerId)) return false;
            if (UnderTopHud(character)) return false;
            if (!hasState || !InRound(state.phase)) return true;
            HS_Role other = RoleOf(character.OwnerId), me = MyRole;
            return Seeks(other) == Seeks(me) || me == HS_Role.None;
        }

        /// <summary>
        /// Whether a character's name tag would land under the top HUD: in the round card's column at any
        /// time, and anywhere in the top band during the results (the banner and summary card are up then).
        /// </summary>
        bool UnderTopHud(GameCharacter character) {
            Camera cam = Camera.main;
            if (cam == null) return false;
            Vector3 p = cam.WorldToViewportPoint(character.transform.position + Vector3.up * nameTagHeight);
            if (p.z <= 0f || p.y < nameTagTopBand) return false;
            return (hasState && state.phase == HS_Phase.Results) || Mathf.Abs(p.x - 0.5f) < roundCardHalfWidth;
        }

        /// <summary>Whether this round's reveal labels a survivor with this client id (yours is never labelled).</summary>
        bool IsRevealed(int clientId) {
            if (spotsRound != state.round || clientId == MyId) return false;
            foreach (var spot in spots) if (spot.clientId == clientId) return true;
            return false;
        }

        void Update() {
            AnimatePointsPopup();
            if (manager == null && InstanceFinder.ClientManager != null) {
                manager = InstanceFinder.ClientManager;
                manager.RegisterBroadcast<HS_StateBroadcast>(OnState);
                manager.RegisterBroadcast<HS_TagBroadcast>(OnTag);
                manager.RegisterBroadcast<HS_PingBroadcast>(OnPing);
                manager.RegisterBroadcast<HS_ResultBroadcast>(OnResult);
                manager.RegisterBroadcast<HS_TauntBroadcast>(OnTaunt);
                manager.RegisterBroadcast<HS_RevealBroadcast>(OnReveal);
                manager.RegisterBroadcast<HS_PointsBroadcast>(OnPoints);
                manager.RegisterBroadcast<HS_RoundRecapBroadcast>(OnRecap);
                manager.RegisterBroadcast<HS_EventBroadcast>(OnEvent);
                manager.RegisterBroadcast<HS_DoorBroadcast>(OnDoor);
            }
            if (manager != null && manager.Started && !hasState && Time.unscaledTime > nextRequest) {
                nextRequest = Time.unscaledTime + StateRequestSeconds;
                manager.Broadcast(new HS_StateRequest());
            }
            if (toast.isVisible && Time.unscaledTime > toastUntil) Show(toast, false, toastFadeOutSeconds);
            RefreshAlert();
            while (feed.Count > 0 && (Time.unscaledTime > feed.Peek().until || feed.Count > feedLines)) Destroy(feed.Dequeue().row.gameObject);
            for (int i = pings.Count - 1; i >= 0; i--) {
                if (Time.unscaledTime < pings[i].until) continue;
                if (pings[i].marker != null) Destroy(pings[i].marker);
                pings.RemoveAt(i);
            }
            if (!hasState) return;
            if (lastHiderAt >= 0f && Time.unscaledTime >= lastHiderAt) { lastHiderAt = -1f; AnnounceLastHider(MyRole); }
            if (eventToastAt >= 0f && Time.unscaledTime >= eventToastAt) {
                // The event's help follows its title, so the chip, the title and the toast never stack in one column.
                eventToastAt = -1f;
                if (activeEvent == eventToastKind) Toast(EventHelp(eventToastKind, MyRole), EventIcon(eventToastKind), null, ToastLong);
            }
            RefreshTimer();
            RefreshPrompt();
            RefreshTauntPrompt();
            RefreshEventChip();
            if (Time.unscaledTime > nextLocation) { nextLocation = Time.unscaledTime + LocationRefresh; RefreshLocation(); }
        }

        void Show(CanvasGroupController group, bool visible, float? duration = null) {
            if (group == null || group.isVisible == visible) return;
            group.TweenAlpha(visible ? 1f : 0f, duration ?? Theme.fadeDuration);
        }

        /// <summary>Seekers see nothing at all while hiders hide: the camera stops drawing the world.</summary>
        void SetBlind(bool blind) {
            if (blindfold.activeSelf != blind) blindfold.SetActive(blind);
            // The level chip and challenges sit above this canvas; keep the blindfold clean (toasts wait until it lifts).
            if (retentionHud != null) retentionHud.SetHidden(blind);
            var cam = Camera.main;
            if (cam == null) return;
            if (blind && cam.cullingMask != 0) { savedMask = cam.cullingMask; cam.cullingMask = 0; } else if (!blind && cam.cullingMask == 0) cam.cullingMask = savedMask;
        }

        /// <summary>
        /// The blindfold's "today" lines: the daily twist, the next unlock and the first unfinished challenge,
        /// since the retention HUD (and the J panel) is hidden under the blindfold.
        /// </summary>
        void RefreshBlindToday() {
            if (blindToday == null) return;
            var text = new StringBuilder();
            string accent = UITheme.ToRichTextHex(Theme.warning), muted = UITheme.ToRichTextHex(Theme.textMuted);
            if (state.featuredEvent != HS_RoundEvent.None)
                text.Append("<color=#").Append(accent).Append(">TODAY</color>  ").Append(HS_Daily.Describe(state.featuredEvent));
            if (retentionHud != null && retentionHud.HasSnapshot) {
                var snapshot = retentionHud.Snapshot;
                if (snapshot.hasNextUnlock)
                    AppendLine(text).Append("<color=#").Append(accent).Append(">NEXT</color>  Level ").Append(snapshot.nextUnlock.level).Append(": ").Append(snapshot.nextUnlock.title)
                        .Append(" <color=#").Append(muted).Append(">(").Append(snapshot.levelXp).Append('/').Append(snapshot.levelXpNeeded).Append(" XP)</color>");
                if (snapshot.challenges != null)
                    foreach (var challenge in snapshot.challenges) {
                        if (challenge.done) continue;
                        AppendLine(text).Append("<color=#").Append(accent).Append(">CHALLENGE</color>  ").Append(challenge.text)
                            .Append(" <color=#").Append(muted).Append(">(").Append(challenge.progress).Append('/').Append(challenge.target).Append(")</color>");
                        break;
                    }
            }
            string result = text.ToString();
            if (blindToday.text != result) blindToday.text = result;
        }

        static StringBuilder AppendLine(StringBuilder text) => text.Length > 0 ? text.Append('\n') : text;

        // ---------------------------------------------------------------- messages
        void OnState(HS_StateBroadcast message, Channel channel) {
            state = message;
            hasState = true;
            stateAt = Time.unscaledTime;
            roles.Clear();
            if (message.roles != null) foreach (var r in message.roles) roles[r.clientId] = r.role;
            HS_Role me = MyRole;

            RefreshRoundCard();
            RefreshRoleCard(me);
            bool blind = message.phase == HS_Phase.Hiding && Seeks(me);
            SetBlind(blind);
            if (blind) {
                blindCountdown.text = message.secondsLeft.ToString();
                RefreshBlindToday();
            }
            // The state also carries the running event, so a late joiner (or a missed message) still sees it.
            if (message.activeEvent != activeEvent || (activeEvent != HS_RoundEvent.None && Mathf.Abs(EventSecondsLeft - message.eventSecondsLeft) > 1))
                SetEvent(message.activeEvent, message.eventSecondsLeft, false);

            if (message.featuredEvent != shownFeatured) ShowFeatured(message.featuredEvent);
            SyncDoors(message.closedDoors);
            if (message.phase != lastPhase) {
                OnPhaseChanged(message.phase, me);
                lastPhase = message.phase;
            }
            if (message.phase == HS_Phase.Seeking && message.hidersLeft == 1 && message.hidersAtStart > 1 && !lastHiderAnnounced) {
                // The state that says "one left" arrives with the tag moment: let that land first.
                lastHiderAnnounced = true;
                lastHiderAt = Time.unscaledTime + lastHiderDelay;
            }
        }

        void OnPhaseChanged(HS_Phase phase, HS_Role me) {
            switch (phase) {
                case HS_Phase.Hiding:
                    ClearPings();
                    StopBeacons();
                    spots = System.Array.Empty<HS_HidingSpot>();
                    lastHiderAnnounced = false;
                    lastHiderAt = -1f;
                    tauntsUsed = 0;
                    lastTauntAt = float.NegativeInfinity;
                    tauntPendingUntil = 0f;
                    SetPoints(0, false);
                    Toast(me == HS_Role.Hider ? "Run and hide!" : "You're seeking. Wait for the countdown...", me == HS_Role.Hider ? hiderIcon : seekerIcon, startSound, ToastStart);
                    break;
                case HS_Phase.Seeking:
                    if (Seeks(me)) GameSfx.Play(SfxCue.Go);
                    Toast(Seeks(me) ? "GO! Find them all. Keys 1-3: abilities." : "Stay hidden! R taunts, keys 1-3: abilities.", seekingIcon, Seeks(me) ? null : startSound, ToastLong);
                    break;
            }
            bool results = phase == HS_Phase.Results;
            if (results) {
                bool mySideWon = ShowResultsBanner(me);
                if (me != HS_Role.None) GameSfx.Play(mySideWon ? SfxCue.Win : SfxCue.Lose);
                ClearFeed();
                RefreshSpots();
                RefreshRecap();
            } else StopBeacons();
            Show(banner, results);
            Show(pointsChip, InRound(phase) && me != HS_Role.None);
        }

        void RefreshRoundCard() {
            (Sprite icon, string label, Color color) = state.phase switch {
                HS_Phase.Hiding => (hidingIcon, "HIDE", Theme.warning),
                HS_Phase.Seeking => (seekingIcon, "SEEK", Theme.danger),
                HS_Phase.Results => (resultsIcon, "ROUND OVER", Theme.accent),
                HS_Phase.Intermission => (waitingIcon, $"ROUND {state.round + 1}", Theme.accent),
                _ => (waitingIcon, "WAITING", Theme.textSecondary),
            };
            phaseIcon.sprite = icon;
            phaseIcon.color = color;
            phaseLabel.text = label;
            phaseLabel.color = color;
            timerFill.color = color;
            int seekers = roles.Values.Count(Seeks);
            hidersLabel.text = InRound(state.phase) || state.phase == HS_Phase.Results ? $"{state.hidersLeft}<size=70%><color=#{UITheme.ToRichTextHex(Theme.textMuted)}>/{state.hidersAtStart}</color></size>" : "-";
            seekersLabel.text = InRound(state.phase) || state.phase == HS_Phase.Results ? seekers.ToString() : "-";
            Show(roundCard, true);
        }

        void RefreshRoleCard(HS_Role me) {
            bool inRound = InRound(state.phase);
            (Sprite icon, string title, Color color) = me switch {
                HS_Role.Hider when inRound => (hiderIcon, "HIDER", Theme.success),
                HS_Role.Seeker when inRound => (seekerIcon, "SEEKER", Theme.danger),
                HS_Role.Caught when inRound => (caughtIcon, "FOUND", Theme.warning),
                _ when inRound => (spectatorIcon, "SPECTATING", Theme.textSecondary),
                _ => (infoIcon, "GET READY", Theme.accent),
            };
            roleIcon.sprite = icon;
            roleIcon.color = color;
            roleAccent.color = color;
            roleTitle.text = title;
            roleTitle.color = color;
            roleHint.text = Hint(me);
            Show(roleCard, state.phase != HS_Phase.Results);
        }

        /// <summary>
        /// Today's featured event (the daily twist) in the challenges panel (J), next to the countdown to
        /// tomorrow's challenges, so the panel says what is different about today's rounds too.
        /// </summary>
        void ShowFeatured(HS_RoundEvent featured) {
            shownFeatured = featured;
            if (retentionHud == null) return;
            var panel = retentionHud.GetComponentInChildren<RetentionChallengesPanel>(true);
            if (panel == null) return;
            string today = featured == HS_RoundEvent.None ? "" : $"{HS_Daily.Title(featured)} today  |  ";
            panel.resetHoursFormat = today + "New in {0}h {1:00}m";
            panel.resetMinutesFormat = today + "New in {0}m {1:00}s";
        }

        string Hint(HS_Role me) => (state.phase, me) switch {
            (HS_Phase.Waiting, _) when state.featuredEvent != HS_RoundEvent.None =>
                $"Today is {HS_Daily.Title(state.featuredEvent)}: {HS_Daily.Bonus(state.featuredEvent)}. J: challenges.",
            (HS_Phase.Waiting, _) => "The round starts as soon as enough players are here. J shows today's challenges.",
            (HS_Phase.Intermission, _) when state.featuredEvent != HS_RoundEvent.None =>
                HS_Daily.Describe(state.featuredEvent),
            (HS_Phase.Intermission, _) => "One in four players will seek. Everyone else hides. Level up to unlock abilities.",
            (HS_Phase.Hiding, HS_Role.Hider) => "Find a spot before the seekers open their eyes. E shuts a closet door behind you.",
            (HS_Phase.Hiding, _) => "Wait here. The hiders are hiding.",
            (HS_Phase.Seeking, HS_Role.Hider) => "Stay hidden for points. Shut empty closets (E) to bluff. R taunts.",
            (HS_Phase.Seeking, HS_Role.Seeker) => "E or click tags. E opens closets: search every room. Keys 1-3: abilities.",
            (HS_Phase.Seeking, HS_Role.Caught) => "You were found! Tag the rest for points: your seeker abilities are on 1-3.",
            _ => "",
        };

