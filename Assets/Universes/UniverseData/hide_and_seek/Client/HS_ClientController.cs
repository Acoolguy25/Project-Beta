        void Awake() {
            map = GetComponentInParent<HS_Map>();
            feedTemplate.gameObject.SetActive(false);
            blindfold.SetActive(false);
            if (blindMapName != null && map != null) blindMapName.text = map.mapName;
            Show(roundCard, false, 0f);
            Show(roleCard, false, 0f);
            Show(locationChip, false, 0f);
            Show(tagPrompt, false, 0f);
            Show(tauntPrompt, false, 0f);
            Show(toast, false, 0f);
            Show(alert, false, 0f);
            Show(banner, false, 0f);
        }

        void OnEnable() {
            ToolControls.interactPressed += TryTag;
            ToolControls.primaryPressed += TryTag;
            ToolControls.reloadToolPressed += TryTaunt;
            NameTagManager.CharacterTagFilter = ShowTag;
        }

        void OnDisable() {
            ToolControls.interactPressed -= TryTag;
            ToolControls.primaryPressed -= TryTag;
            ToolControls.reloadToolPressed -= TryTaunt;
            if (NameTagManager.CharacterTagFilter == ShowTag) NameTagManager.CharacterTagFilter = null;
            if (blindfold != null) SetBlind(false);
        }

        void OnDestroy() {
            ClearPings();
            StopBeacons();
            if (manager == null) return;
            manager.UnregisterBroadcast<HS_StateBroadcast>(OnState);
            manager.UnregisterBroadcast<HS_TagBroadcast>(OnTag);
            manager.UnregisterBroadcast<HS_PingBroadcast>(OnPing);
            manager.UnregisterBroadcast<HS_ResultBroadcast>(OnResult);
            manager.UnregisterBroadcast<HS_TauntBroadcast>(OnTaunt);
            manager.UnregisterBroadcast<HS_RevealBroadcast>(OnReveal);
        }

        static bool InRound(HS_Phase phase) => phase is HS_Phase.Hiding or HS_Phase.Seeking;
        int MyId => manager != null && manager.Connection != null ? manager.Connection.ClientId : -1;
        HS_Role MyRole => roles.TryGetValue(MyId, out var r) ? r : HS_Role.None;
        HS_Role RoleOf(int clientId) => roles.TryGetValue(clientId, out var r) ? r : HS_Role.None;

        bool ShowTag(GameCharacter character) {
            // In the results a survivor's green reveal label is their name: one name each, not two.
            if (hasState && state.phase == HS_Phase.Results && IsRevealed(character.OwnerId)) return false;
            if (!hasState || !InRound(state.phase)) return true;
            HS_Role other = RoleOf(character.OwnerId), me = MyRole;
            return Seeks(other) == Seeks(me) || me == HS_Role.None;
        }

        /// <summary>Whether this round's reveal labels a survivor with this client id (yours is never labelled).</summary>
        bool IsRevealed(int clientId) {
            if (spotsRound != state.round || clientId == MyId) return false;
            foreach (var spot in spots) if (spot.clientId == clientId) return true;
            return false;
        }

        void Update() {
            if (manager == null && InstanceFinder.ClientManager != null) {
                manager = InstanceFinder.ClientManager;
                manager.RegisterBroadcast<HS_StateBroadcast>(OnState);
                manager.RegisterBroadcast<HS_TagBroadcast>(OnTag);
                manager.RegisterBroadcast<HS_PingBroadcast>(OnPing);
                manager.RegisterBroadcast<HS_ResultBroadcast>(OnResult);
                manager.RegisterBroadcast<HS_TauntBroadcast>(OnTaunt);
                manager.RegisterBroadcast<HS_RevealBroadcast>(OnReveal);
            }
            if (manager != null && manager.Started && !hasState && Time.unscaledTime > nextRequest) {
                nextRequest = Time.unscaledTime + StateRequestSeconds;
                manager.Broadcast(new HS_StateRequest());
            }
            if (toast.isVisible && Time.unscaledTime > toastUntil) Show(toast, false, toastFadeOutSeconds);
            RefreshAlert();
            while (feed.Count > 0 && (Time.unscaledTime > feed.Peek().until || feed.Count > feedLines)) Destroy(feed.Dequeue().row.gameObject);
            for (int i = pings.Count - 1; i >= 0; i--) {
                if (Time.unscaledTime < pings[i].until) continue;
                if (pings[i].marker != null) Destroy(pings[i].marker);
                pings.RemoveAt(i);
            }
            if (!hasState) return;
            if (lastHiderAt >= 0f && Time.unscaledTime >= lastHiderAt) { lastHiderAt = -1f; AnnounceLastHider(MyRole); }
            RefreshTimer();
            RefreshPrompt();
            RefreshTauntPrompt();
            if (Time.unscaledTime > nextLocation) { nextLocation = Time.unscaledTime + LocationRefresh; RefreshLocation(); }
        }

        void Show(CanvasGroupController group, bool visible, float? duration = null) {
            if (group == null || group.isVisible == visible) return;
            group.TweenAlpha(visible ? 1f : 0f, duration ?? Theme.fadeDuration);
        }

        /// <summary>Seekers see nothing at all while hiders hide: the camera stops drawing the world.</summary>
        void SetBlind(bool blind) {
            if (blindfold.activeSelf != blind) blindfold.SetActive(blind);
            var cam = Camera.main;
            if (cam == null) return;
            if (blind && cam.cullingMask != 0) { savedMask = cam.cullingMask; cam.cullingMask = 0; } else if (!blind && cam.cullingMask == 0) cam.cullingMask = savedMask;
        }

        // ---------------------------------------------------------------- input
        void TryTag() {
            if (manager == null || !hasState || state.phase != HS_Phase.Seeking || !Seeks(MyRole)) return;
            manager.Broadcast(new HS_TagRequest { round = state.round });
        }

        /// <summary>Hiders: ask to taunt. The server checks the cooldown and allowance again and answers with <see cref="HS_TauntBroadcast"/>.</summary>
        void TryTaunt() {
            if (manager == null || !hasState || !CanTauntNow()) return;
            manager.Broadcast(new HS_TauntRequest { round = state.round });
            // Until the server confirms, wait a moment before allowing another request.
            tauntPendingUntil = Time.unscaledTime + TauntRetrySeconds;
        }

        float SinceLastTaunt => Time.unscaledTime - lastTauntAt;

        bool CanTauntNow() => Time.unscaledTime >= tauntPendingUntil && HS_Rules.CanTaunt(state.phase, MyRole, SinceLastTaunt, tauntsUsed);

        LocalCharacter NearestHider() {
            var me = LocalPlayer.Character;
            if (me == null) return null;
            float distance = float.MaxValue;
            LocalCharacter best = null;
            foreach (var pair in roles) {
                if (pair.Value != HS_Role.Hider) continue;
                var hider = CharacterLookup.ByClientId(pair.Key);
                if (hider == null) continue;
                float d = Vector3.Distance(me.transform.position, hider.transform.position);
                if (d < distance) { distance = d; best = hider; }
            }
            return best;
        }

        void RefreshPrompt() {
            bool seeking = state.phase == HS_Phase.Seeking && Seeks(MyRole);
            if (!seeking) promptHider = null;
            else if (Time.unscaledTime >= nextHiderScan) {
                // The lookup walks every character, so do it a few times a second, not every frame.
                nextHiderScan = Time.unscaledTime + HiderScanSeconds;
                promptHider = NearestHider();
            }
            var me = LocalPlayer.Character;
            bool show = promptHider != null && me != null && Vector3.Distance(me.transform.position, promptHider.transform.position) <= HS_Rules.TagRange;
            // Name the hider only once they are in reach, so a fading prompt never shows someone far away.
            if (show && promptHider != labelledHider) {
                labelledHider = promptHider;
                tagLabel.text = $"Tag <b>{promptHider.DisplayName}</b>";
            }
            Show(tagPrompt, show);
        }

        void RefreshTauntPrompt() {
            bool show = state.phase == HS_Phase.Seeking && MyRole == HS_Role.Hider;
            Show(tauntPrompt, show);
            if (!show) return;
            int left = HS_Rules.TauntsPerRound - tauntsUsed;
            float charge = Mathf.Clamp01(SinceLastTaunt / HS_Rules.TauntCooldown);
            float fill = left <= 0 ? 0f : charge;
            if (tauntFill.fillAmount != fill) tauntFill.fillAmount = fill;
            // 0 = none left, -1 = recharging, otherwise the count: the label only changes with this.
            int key = left <= 0 ? 0 : charge < 1f ? -1 : left;
            if (key == shownTaunt) return;
            shownTaunt = key;
            tauntLabel.text = key == 0 ? "No taunts left" : key < 0 ? "Taunt recharging" : $"Taunt <size=75%>({left} left)</size>";
        }

        void RefreshLocation() {
            var me = LocalPlayer.Character;
            string area = me != null && map != null ? map.AreaAt(me.transform.position) : "";
            bool show = area.Length > 0 && state.phase != HS_Phase.Results && !blindfold.activeSelf;
            if (show && area != shownArea) locationLabel.text = shownArea = area;
            Show(locationChip, show);
        }

        // ---------------------------------------------------------------- messages
        void OnState(HS_StateBroadcast message, Channel channel) {
            state = message;
            hasState = true;
            stateAt = Time.unscaledTime;
            roles.Clear();
            if (message.roles != null) foreach (var r in message.roles) roles[r.clientId] = r.role;
            HS_Role me = MyRole;

            RefreshRoundCard();
            RefreshRoleCard(me);
            bool blind = message.phase == HS_Phase.Hiding && Seeks(me);
            SetBlind(blind);
            if (blind) blindCountdown.text = message.secondsLeft.ToString();

            if (message.phase != lastPhase) {
                OnPhaseChanged(message.phase, me);
                lastPhase = message.phase;
            }
            if (message.phase == HS_Phase.Seeking && message.hidersLeft == 1 && message.hidersAtStart > 1 && !lastHiderAnnounced) {
                // The state that says "one left" arrives with the tag moment: let that land first.
                lastHiderAnnounced = true;
                lastHiderAt = Time.unscaledTime + lastHiderDelay;
            }
        }

        void OnPhaseChanged(HS_Phase phase, HS_Role me) {
            switch (phase) {
                case HS_Phase.Hiding:
                    ClearPings();
                    StopBeacons();
                    spots = System.Array.Empty<HS_HidingSpot>();
                    lastHiderAnnounced = false;
                    lastHiderAt = -1f;
                    tauntsUsed = 0;
                    lastTauntAt = float.NegativeInfinity;
                    tauntPendingUntil = 0f;
                    Toast(me == HS_Role.Hider ? "Run and hide!" : "You're seeking. Wait for the countdown...", me == HS_Role.Hider ? hiderIcon : seekerIcon, startSound, ToastStart);
                    break;
                case HS_Phase.Seeking:
                    if (Seeks(me)) GameSfx.Play(SfxCue.Go);
                    Toast(Seeks(me) ? "GO! Find them all." : "The seekers are coming. Stay hidden! Press R to taunt.", seekingIcon, Seeks(me) ? null : startSound, ToastLong);
                    break;
            }
            bool results = phase == HS_Phase.Results;
            if (results) {
                bool hidersWin = state.hidersLeft > 0;
                bannerTitle.text = hidersWin ? "HIDERS WIN" : "SEEKERS WIN";
                bannerSubtitle.text = hidersWin ? $"{state.hidersLeft} of {state.hidersAtStart} stayed hidden" : "Everyone was found";
                Color accent = hidersWin ? Theme.success : Theme.danger;
                bannerAccent.color = accent;
                bannerIcon.sprite = hidersWin ? hiderIcon : seekerIcon;
                bannerIcon.color = accent;
                if (me != HS_Role.None) GameSfx.Play(hidersWin == (me == HS_Role.Hider) ? SfxCue.Win : SfxCue.Lose);
                RefreshSpots();
            } else StopBeacons();
            Show(banner, results);
        }

        void RefreshRoundCard() {
            (Sprite icon, string label, Color color) = state.phase switch {
                HS_Phase.Hiding => (hidingIcon, "HIDE", Theme.warning),
                HS_Phase.Seeking => (seekingIcon, "SEEK", Theme.danger),
                HS_Phase.Results => (resultsIcon, "ROUND OVER", Theme.accent),
                HS_Phase.Intermission => (waitingIcon, $"ROUND {state.round + 1}", Theme.accent),
                _ => (waitingIcon, "WAITING", Theme.textSecondary),
            };
            phaseIcon.sprite = icon;
            phaseIcon.color = color;
            phaseLabel.text = label;
            phaseLabel.color = color;
            timerFill.color = color;
            int seekers = roles.Values.Count(Seeks);
            hidersLabel.text = InRound(state.phase) || state.phase == HS_Phase.Results ? $"{state.hidersLeft}<size=70%><color=#{UITheme.ToRichTextHex(Theme.textMuted)}>/{state.hidersAtStart}</color></size>" : "-";
            seekersLabel.text = InRound(state.phase) || state.phase == HS_Phase.Results ? seekers.ToString() : "-";
            Show(roundCard, true);
        }

        void RefreshRoleCard(HS_Role me) {
            bool inRound = InRound(state.phase);
            (Sprite icon, string title, Color color) = me switch {
                HS_Role.Hider when inRound => (hiderIcon, "HIDER", Theme.success),
                HS_Role.Seeker when inRound => (seekerIcon, "SEEKER", Theme.danger),
                HS_Role.Caught when inRound => (caughtIcon, "FOUND", Theme.warning),
                _ when inRound => (spectatorIcon, "SPECTATING", Theme.textSecondary),
                _ => (infoIcon, "GET READY", Theme.accent),
            };
            roleIcon.sprite = icon;
            roleIcon.color = color;
            roleAccent.color = color;
            roleTitle.text = title;
            roleTitle.color = color;
            roleHint.text = Hint(me);
            Show(roleCard, state.phase != HS_Phase.Results);
        }

        string Hint(HS_Role me) => (state.phase, me) switch {
            (HS_Phase.Waiting, _) => "The round starts as soon as enough players are here.",
            (HS_Phase.Intermission, _) => "One in four players will seek. Everyone else hides.",
            (HS_Phase.Hiding, HS_Role.Hider) => "Find a hiding spot before the seekers open their eyes.",
            (HS_Phase.Hiding, _) => "Wait here. The hiders are hiding.",
            (HS_Phase.Seeking, HS_Role.Hider) => "Stay out of sight. Your heart races when a seeker is near. R taunts for XP.",
            (HS_Phase.Seeking, HS_Role.Seeker) => "Find the hiders. Get close and press E or click to tag. Listen for taunts.",
            (HS_Phase.Seeking, HS_Role.Caught) => "You were found! Help the seekers find the rest.",
            _ => "",
        };

        void OnTag(HS_TagBroadcast message, Channel channel) {
            roles[message.hiderId] = HS_Role.Caught;
            AddFeed($"<color=#{UITheme.ToRichTextHex(Theme.danger)}>{message.seekerName}</color> found <color=#{UITheme.ToRichTextHex(Theme.success)}>{message.hiderName}</color>", tagIcon);
            bool tagged = message.hiderId == MyId, tagger = message.seekerId == MyId;
            if (tagged) Toast("You were found! You're a seeker now.", caughtIcon, null, ToastLong);
            else if (tagger) Toast($"Tagged {message.hiderName}!", tagIcon, null, ToastShort);
            if (tagged) RefreshRoleCard(MyRole);
            PlayTagMoment(message.hiderId, tagged, tagger);
        }

        /// <summary>Sting, a poof of smoke where the hider was, a flash and a slow shake for whoever was involved.</summary>
        void PlayTagMoment(int hiderId, bool tagged, bool tagger) {
            LocalCharacter hider = CharacterLookup.ByClientId(hiderId);
            if (tagged || tagger) {
                GameSfx.Play(tagSting);
                ScreenFx.Flash(tagged ? taggedFlash : taggerFlash, flashSeconds);
                CameraShake.Kick(tagged ? tagShake : tagShake * taggerShakeFactor, tagShakeSeconds);
            }
            if (hider == null) return;
            Vector3 feet = hider.transform.position;
            if (!tagged && !tagger) {
                GameSfx.PlayAt(tagSting, feet);
                CameraShake.Explosion(feet, tagShakeRadius, tagShake * bystanderShakeFactor, tagShakeSeconds);
            }
            // Layered puffs from feet to head swallow the robot (one stretched puff showed hard edges).
            for (int i = 0; i < poofPasses; i++) GameFx.Poof(feet, poofHeight, poofTint, poofScale);
            HitFlash.On(hider, Color.white);
        }

        void AnnounceLastHider(HS_Role me) {
            if (state.phase != HS_Phase.Seeking) return;
            GameSfx.Play(lastHiderSting);
            GameSfx.Play(lastHiderVoice);
            ShowAlert(me == HS_Role.Hider ? "YOU'RE THE LAST HIDER!" : "LAST HIDER!", Theme.danger, lastHiderTextSeconds);
            string name = roles.Where(r => r.Value == HS_Role.Hider).Select(r => CharacterLookup.ByClientId(r.Key)).FirstOrDefault(c => c != null)?.DisplayName;
            AddFeed(name != null ? $"Last hider: <color=#{UITheme.ToRichTextHex(Theme.success)}>{name}</color>" : "One hider left", hiderIcon);
        }

        void OnPing(HS_PingBroadcast message, Channel channel) {
            ClearPings();
            if (map == null || map.pingPrefab == null || message.positions == null) return;
            foreach (var p in message.positions)
                pings.Add((Instantiate(map.pingPrefab, p, Quaternion.identity, map.transform), Time.unscaledTime + pingSeconds));
            Toast("PING! Hiders were spotted near the red beacons.", pingIcon, pingSound, ToastLong);
        }

        void OnResult(HS_ResultBroadcast message, Channel channel) => Toast(message.message, message.accepted ? pingIcon : infoIcon, message.accepted ? pingSound : null, ToastMedium);

        void OnTaunt(HS_TauntBroadcast message, Channel channel) {
            if (message.clientId != MyId) {
                GameSfx.PlayAt(tauntSound, message.position);
                // Seekers (and other hiders) also see where it came from, if they are looking that way.
                GameFx.Play(FxKind.ShockwaveRing, message.position, Theme.warning, tauntRingScale);
                FloatingText.Callout(message.position + Vector3.up * tauntMarkHeight, "!", Theme.warning, 1f, tauntMarkSeconds);
                return;
            }
            tauntsUsed = message.used;
            tauntPendingUntil = 0f;
            if (message.correction) return;
            GameSfx.Play(tauntSound);
            lastTauntAt = Time.unscaledTime;
            // A taunt is rare, so a string per popup is fine; the callout style can stay up longer than a number.
            FloatingText.Callout(message.position + Vector3.up * tauntPopupHeight, $"+{message.xp} XP", message.brave ? Theme.warning : Theme.success, tauntPopupSize, tauntPopupSeconds);
            if (message.brave) Toast("Brave taunt! A seeker is close.", tauntIcon, null, ToastMedium); // the popup carries the XP
        }

        void OnReveal(HS_RevealBroadcast message, Channel channel) {
            spots = message.spots ?? System.Array.Empty<HS_HidingSpot>();
            spotsRound = message.round;
            StopBeacons();
            // Names stay up for the whole results phase and draw over the world, so everyone can see
            // where the survivors were from where they stand. Your own spot needs no label.
            float seconds = Mathf.Max(1f, message.seconds);
            foreach (var spot in spots) {
                beacons.Add(GameFx.Start(FxKind.BeaconBeam, spot.position, Theme.success, revealBeaconScale));
                if (spot.clientId != MyId)
                    FloatingText.Callout(spot.position + Vector3.up * revealLabelHeight, spot.name, Theme.success, revealLabelSize, seconds);
            }
            RefreshSpots();
        }

        /// <summary>Fills the banner's "who hid where" list from the latest reveal.</summary>
        void RefreshSpots() {
            if (bannerSpots == null) return;
            if (spots.Length == 0 || spotsRound != state.round) { bannerSpots.text = ""; return; }
            var text = new StringBuilder();
            string hex = UITheme.ToRichTextHex(Theme.success);
            int shown = Mathf.Min(spots.Length, bannerSpotLines);
            for (int i = 0; i < shown; i++) {
                string area = map != null ? map.AreaAt(spots[i].position) : "";
                if (i > 0) text.Append('\n');
                text.Append("<color=#").Append(hex).Append('>').Append(spots[i].name).Append("</color> hid in ").Append(area.Length > 0 ? $"the {area}" : "a secret spot");
            }
            if (spots.Length > shown) text.Append($"\n+{spots.Length - shown} more");
            bannerSpots.text = text.ToString();
        }

        void StopBeacons() {
            foreach (var beacon in beacons) beacon.Stop();
            beacons.Clear();
        }

        void AddFeed(string text, Sprite icon) {
            var row = Instantiate(feedTemplate, feedList);
            row.gameObject.SetActive(true);
            row.Set(text, icon);
            row.transform.SetAsFirstSibling();
            feed.Enqueue((row, Time.unscaledTime + feedSeconds));
        }

        void ClearPings() {
            foreach (var p in pings) if (p.marker != null) Destroy(p.marker);
            pings.Clear();
        }

        void RefreshTimer() {
            bool timed = state.phase is HS_Phase.Intermission or HS_Phase.Hiding or HS_Phase.Seeking or HS_Phase.Results;
            int left = Mathf.Max(0, state.secondsLeft - Mathf.FloorToInt(Time.unscaledTime - stateAt));
            int clock = timed ? left : -2;
            if (clock != shownClock) {
                shownClock = clock;
                timerLabel.text = timed ? RoundFormat.Clock(left) : "--:--";
            }
            timerFill.fillAmount = timed && state.phaseSeconds > 0 ? Mathf.Clamp01((left - (Time.unscaledTime - stateAt) % 1f) / state.phaseSeconds) : 0f;
            if (state.phase == HS_Phase.Hiding) TickCountdown(left);
            else lastTickSecond = -1;
        }

        /// <summary>Blind seekers hear every second tick by; everyone hears the last few seconds beep.</summary>
        void TickCountdown(int left) {
            if (left == lastTickSecond || left <= 0) return;
            bool first = lastTickSecond < 0;
            lastTickSecond = left;
            if (blindfold.activeSelf) blindCountdown.text = left.ToString();
            if (first) return;
            if (left <= countdownBeepsFrom) GameSfx.Play(SfxCue.CountdownBeep);
            else if (blindfold.activeSelf) GameSfx.Play(blindTick);
        }

        void ShowAlert(string message, Color color, float seconds) {
            if (alert == null) return;
            alertLabel.text = message;
            alertLabel.color = color;
            alertAt = Time.unscaledTime;
            alertUntil = alertAt + seconds;
            Show(alert, true, 0.08f);
        }

        /// <summary>Pops the alert in (overshoot to full size) and fades it when its time is up.</summary>
        void RefreshAlert() {
            if (alertAt < 0f) return;
            float age = Time.unscaledTime - alertAt;
            float t = Mathf.Clamp01(age / alertPopSeconds);
            alertLabel.transform.localScale = Vector3.one * Mathf.LerpUnclamped(alertPopScale, 1f, 1f - (1f - t) * (1f - t));
            if (Time.unscaledTime > alertUntil) {
                Show(alert, false);
                alertAt = -1f;
            }
        }

        void Toast(string message, Sprite icon, SfxSound sound, float seconds) {
            toastLabel.text = message;
            toastIcon.sprite = icon != null ? icon : infoIcon;
            toastUntil = Time.unscaledTime + seconds;
            Show(toast, true);
            if (sound != null) GameSfx.Play(sound);
        }
    }
