#if !UNITY_SERVER
using System;
using RyanAssets.GameFeel;
using RyanAssets.Input;
using RyanAssets.Retention.Client;
using RyanAssets.UI.GameHud;
using TMPro;
using UnityEngine;
using UnityEngine.InputSystem;
using UnityEngine.UI;

namespace Universes.UniverseData.dot_invaders.Client {
    /// <summary>
    /// Dot Invaders' screen HUD: your team, the match clock, the board, your bases and troops, the
    /// power bar, a short controls reminder, the end-of-match banner and match timeline; bottom right, your
    /// send amount (keys 1 to 4), rank and rating, your perks (P opens the picker) and the Overdrive button (X). The retention kit's HUD
    /// (level chip, challenges, summary card) is nested in the same prefab. Presentation only; fed
    /// snapshots and the player's profile by <see cref="DI_ClientController"/>. Generated by DI_Authoring.
    /// </summary>
    public sealed class DI_HUD : MonoBehaviour {
        [Header("Status")]
        [SerializeField] Image teamDisc;
        [SerializeField] TMP_Text teamName;
        [SerializeField] HudChip clock, bases, troops;
        [Tooltip("The board being played and the NPC tier.")]
        [SerializeField] HudChip board;
        [SerializeField] DI_PowerBar powerBar;
        [SerializeField] HudPopup controls;

        [Header("Commander (bottom right)")]
        [SerializeField] RectTransform commander;
        [SerializeField] HudChip rank;
        [SerializeField] HudChip perks;
        [SerializeField] Button perksButton;
        [SerializeField] DI_PerkPanel perkPanel;
        [SerializeField] InputAction perksInput = new("Perks", InputActionType.Button, "<Keyboard>/p");
        [Tooltip("{0} equipped perks, {1} slots.")]
        [SerializeField] string perksFormat = "Perks {0}/{1}";
        [Tooltip("{0} the level the first perk unlocks at.")]
        [SerializeField] string noPerksFormat = "Perks at Lv {0}";
        [Tooltip("{0} rank name, {1} rating.")]
        [SerializeField] string rankFormat = "{0}  <color=#C8D0DC>{1}</color>";
        [Tooltip("Appended while a higher rank exists, so the next goal is always on screen. {0} next rank, {1} its rating.")]
        [SerializeField] string nextRankFormat = "  <size=80%><color=#8C96AA>next {0} at {1}</color></size>";

        [Header("Send amount")]
        [Tooltip("Shows the share of each base an order sends; clicking it steps to the next amount.")]
        [SerializeField] HudChip sendAmount;
        [SerializeField] Button sendAmountButton;
        [Tooltip("One key per entry of DI_Rules.SendPercents, in the same order.")]
        [SerializeField] InputAction[] sendAmountInputs = {
            new("Send 25%", InputActionType.Button, "<Keyboard>/1"),
            new("Send 50%", InputActionType.Button, "<Keyboard>/2"),
            new("Send 75%", InputActionType.Button, "<Keyboard>/3"),
            new("Send all", InputActionType.Button, "<Keyboard>/4"),
        };
        [Tooltip("{0} the percentage.")]
        [SerializeField] string sendAmountFormat = "Send {0}%";
        [SerializeField] string sendAllText = "Send all";
        [Tooltip("Chip tint while sending part of each garrison, so a partial send is never forgotten.")]
        [SerializeField] Color partialSendColor = new(1f, 0.79f, 0.29f);
        [SerializeField] Color fullSendColor = new(0.5f, 0.85f, 1f);
        [SerializeField, Min(0f)] float sendAmountPunch = 0.15f;
        [Tooltip("Saved per device, so the choice survives between sessions.")]
        [SerializeField] string sendAmountPrefsKey = "dot_invaders.send_percent";

        [Header("Match timeline")]
        [SerializeField] DI_MatchTimeline timeline;

        [Header("Overdrive")]
        [SerializeField] HudPopup ability;
        [SerializeField] Button abilityButton;
        [SerializeField] Image abilityKey;
        [SerializeField] TMP_Text abilityLabel;
        [SerializeField] InputAction abilityInput = new("Overdrive", InputActionType.Button, "<Keyboard>/x");
        [SerializeField] Color abilityIdleColor = new(0.45f, 0.5f, 0.58f);
        [SerializeField] Color abilityReadyColor = new(1f, 0.82f, 0.25f);
        [SerializeField] Color abilityActiveColor = new(1f, 0.55f, 0.2f);
        [SerializeField] string abilityLockedFormat = "Overdrive in {0}s";
        [SerializeField] string abilityReadyText = "Overdrive ready";
        [SerializeField] string abilityActiveFormat = "OVERDRIVE  {0}s";
        [SerializeField] string abilitySpentText = "Overdrive used";
        [SerializeField, Min(0f)] float abilityReadyPunch = 0.18f;
        [SerializeField, Min(0.01f)] float abilityReadyPunchSeconds = 0.35f;

        [Header("Retention kit")]
        [Tooltip("The nested RetentionHUD prefab instance (level, challenges, summary card).")]
        [SerializeField] RetentionHud retention;

        [Header("Match end")]
        [SerializeField] HudBanner banner;
        [SerializeField] Sprite victoryIcon, defeatIcon, drawIcon;
        [Tooltip("Seconds after the match ends before a rank-up is celebrated, so it follows the win or loss cue.")]
        [SerializeField, Min(0f)] float rankUpDelay = 2.5f;
        [SerializeField, Min(0.1f)] float rankUpTextSeconds = 2.4f;
        [SerializeField, Range(0.1f, 1f)] float rankUpTextSize = 0.4f;
        [SerializeField, Min(0f)] float rankUpPunch = 0.3f;
        [SerializeField, Min(0.01f)] float rankUpPunchSeconds = 0.45f;
        [Tooltip("{0} is the new rank's name.")]
        [SerializeField] string rankUpFormat = "RANK UP  ·  {0}";
        [SerializeField] Color ratingGainColor = new(0.5f, 0.95f, 0.55f);
        [SerializeField] Color ratingLossColor = new(1f, 0.5f, 0.45f);

        bool matchEnded;
        bool hasProfile;
        DI_ProfileBroadcast profile;
        DI_AbilityState abilityState = DI_AbilityState.None;
        float rankUpAt = -1f;
        DI_Rank pendingRank;
        int sendPercent = DI_Rules.FullSendPercent;

        /// <summary>Share of each garrison an order sends, in percent (one of DI_Rules.SendPercents).</summary>
        public int SendPercent => sendPercent;

        /// <summary>The player pressed X or clicked the Overdrive button while it was ready.</summary>
        public event Action AbilityPressed;

        /// <summary>The player picked a new loadout in the perk panel.</summary>
        public event Action<string[]> LoadoutRequested;

        int Level => retention != null ? retention.Level : 1;

        void Awake() {
            if (perksButton != null)
                perksButton.onClick.AddListener(TogglePerks);
            if (abilityButton != null)
                abilityButton.onClick.AddListener(PressAbility);
            if (sendAmountButton != null)
                sendAmountButton.onClick.AddListener(CycleSendAmount);
            sendPercent = LoadSendPercent();
            RefreshSendAmount(false);
            if (perkPanel != null)
                perkPanel.LoadoutRequested += OnLoadoutRequested;
            if (retention != null)
                retention.LevelChanged += OnLevelChanged;
            if (rank != null)
                rank.SetVisible(false);
            if (ability != null)
                ability.HideImmediate();
            RefreshPerksChip();
        }

        void OnDestroy() {
            if (perksButton != null)
                perksButton.onClick.RemoveListener(TogglePerks);
            if (abilityButton != null)
                abilityButton.onClick.RemoveListener(PressAbility);
            if (sendAmountButton != null)
                sendAmountButton.onClick.RemoveListener(CycleSendAmount);
            if (perkPanel != null)
                perkPanel.LoadoutRequested -= OnLoadoutRequested;
            if (retention != null)
                retention.LevelChanged -= OnLevelChanged;
        }

        void OnEnable() {
            perksInput?.Enable();
            abilityInput?.Enable();
            foreach (InputAction input in sendAmountInputs)
                input?.Enable();
        }

        void OnDisable() {
            perksInput?.Disable();
            abilityInput?.Disable();
            foreach (InputAction input in sendAmountInputs)
                input?.Disable();
        }

        void Update() {
            if (rankUpAt >= 0f && Time.unscaledTime >= rankUpAt) {
                rankUpAt = -1f;
                CelebrateRankUp(pendingRank);
            }
            // Keys only count while the board has the keyboard (not while typing in chat or in a menu).
            if (InputService.characterControls == null || !InputService.characterControls.GameplayInputActive)
                return;
            if (perksInput != null && perksInput.WasPressedThisFrame())
                TogglePerks();
            if (abilityInput != null && abilityInput.WasPressedThisFrame())
                PressAbility();
            int options = Mathf.Min(sendAmountInputs.Length, DI_Rules.SendPercents.Length);
            for (int i = 0; i < options; i++)
                if (sendAmountInputs[i] != null && sendAmountInputs[i].WasPressedThisFrame())
                    SetSendPercent(DI_Rules.SendPercents[i]);
        }

        void CycleSendAmount() {
            int index = Array.IndexOf(DI_Rules.SendPercents, sendPercent);
            SetSendPercent(DI_Rules.SendPercents[(index + 1) % DI_Rules.SendPercents.Length]);
        }

        void SetSendPercent(int percent) {
            if (percent == sendPercent)
                return;
            sendPercent = percent;
            try {
                PlayerPrefs.SetInt(sendAmountPrefsKey, percent);
            } catch (Exception exception) {
                Debug.LogWarning($"Dot Invaders: could not save the send amount ({exception.Message}).");
            }
            GameSfx.Play(SfxCue.UiClick);
            RefreshSendAmount(true);
        }

        int LoadSendPercent() {
            int saved = PlayerPrefs.GetInt(sendAmountPrefsKey, DI_Rules.FullSendPercent);
            return Array.IndexOf(DI_Rules.SendPercents, saved) >= 0 ? saved : DI_Rules.FullSendPercent;
        }

        void RefreshSendAmount(bool punch) {
            if (sendAmount == null)
                return;
            bool all = sendPercent >= DI_Rules.FullSendPercent;
            sendAmount.Text = all ? sendAllText : string.Format(sendAmountFormat, sendPercent);
            sendAmount.SetTint(all ? fullSendColor : partialSendColor);
            if (punch)
                Punch.Scale(sendAmount.transform, sendAmountPunch, abilityReadyPunchSeconds);
        }

        public bool ContainsPointer(Vector2 position) =>
            powerBar != null && powerBar.ContainsPointer(position) ||
            perkPanel != null && perkPanel.ContainsPointer(position) ||
            Contains(commander, position) ||
            timeline != null && Contains((RectTransform)timeline.transform, position);

        static bool Contains(RectTransform rect, Vector2 position) =>
            rect != null && rect.gameObject.activeInHierarchy && RectTransformUtility.RectangleContainsScreenPoint(rect, position, null);

        public void SetState(DI_StateBroadcast state, Func<int, Color> teamColor, Func<int, string> teamNameOf) {
            powerBar.SetState(state, teamColor, teamNameOf);
            if (timeline != null)
                timeline.Record(state, teamColor);

            Color mine = teamColor(state.yourTeamId);
            teamDisc.color = mine;
            teamName.text = teamNameOf(state.yourTeamId);
            teamName.color = Color.Lerp(mine, Color.white, 0.3f);

            int seconds = Mathf.Max(0, state.secondsRemaining);
            clock.Text = state.matchEnded ? "Match over" : $"{seconds / 60}:{seconds % 60:00}";
            clock.SetTint(!state.matchEnded && seconds <= 30 ? new Color(1f, 0.45f, 0.4f) : new Color(0.71f, 0.74f, 0.78f));
            if (board != null)
                board.Text = BoardText(state);

            int baseCount = 0, troopCount = 0;
            for (int i = 0; i < state.baseTeams.Length; i++) {
                if (state.baseTeams[i] != state.yourTeamId) continue;
                baseCount++;
                troopCount += state.baseTroops[i];
            }
            bases.Text = baseCount.ToString();
            troops.Text = troopCount.ToString("N0");
            controls.SetVisible(!state.matchEnded);
            SetAbility(state.matchEnded ? DI_AbilityState.None : (DI_AbilityState)state.yourAbilityState, state.yourAbilitySeconds);

            if (state.matchEnded && !matchEnded) {
                bool draw = state.winningTeamId < 0;
                bool won = !draw && state.winningTeamId == state.yourTeamId;
                Color color = draw ? new Color(0.6f, 0.64f, 0.7f) : teamColor(state.winningTeamId);
                string outcome = draw ? "Nobody conquered the board." : $"{teamNameOf(state.winningTeamId)} conquered the board.";
                banner.Show(draw ? drawIcon : won ? victoryIcon : defeatIcon, color,
                    draw ? "DRAW" : won ? "VICTORY!" : "DEFEAT", WithProgress(outcome, state.yourSummary), 0f);
                QueueRankUp(state.yourSummary);
            } else if (!state.matchEnded && matchEnded) {
                banner.Hide();
            }
            matchEnded = state.matchEnded;
        }

        static string BoardText(in DI_StateBroadcast state) {
            string title = DI_BoardLayouts.Find(state.layoutId)?.title ?? "Board";
            return string.IsNullOrEmpty(state.npcTierName) ? title : $"{title}  ·  {state.npcTierName} bots";
        }

        /// <summary>The player's rating, record and loadout, as the server last sent them.</summary>
        public void SetProfile(in DI_ProfileBroadcast next) {
            bool first = !hasProfile;
            int previousRating = profile.rating;
            profile = next;
            hasProfile = true;
            if (rank != null) {
                DI_Rank current = DI_Ranks.Of(next.rating);
                string text = string.Format(rankFormat, current.Name, next.rating);
                if (DI_Ranks.TryNext(next.rating, out DI_Rank goal))
                    text += string.Format(nextRankFormat, goal.Name, goal.MinRating);
                rank.Text = text;
                rank.SetTint(current.Color);
                rank.SetVisible(true);
                if (!first && next.rating != previousRating)
                    Punch.Scale(rank.transform, abilityReadyPunch, abilityReadyPunchSeconds);
            }
            if (perkPanel != null)
                perkPanel.SetProfile(next.perks, Level, next.saved);
            RefreshPerksChip();
        }

        void OnLevelChanged(int level) {
            if (perkPanel != null)
                perkPanel.SetLevel(level);
            RefreshPerksChip();
        }

        void RefreshPerksChip() {
            if (perks == null)
                return;
            int slots = DI_Perks.SlotsAt(Level);
            int equipped = perkPanel != null ? perkPanel.Equipped.Count : 0;
            perks.Text = slots == 0 ? string.Format(noPerksFormat, FirstPerkLevel()) : string.Format(perksFormat, equipped, slots);
        }

        static int FirstPerkLevel() {
            int first = int.MaxValue;
            foreach (DI_PerkDefinition perk in DI_Perks.All)
                first = Mathf.Min(first, perk.UnlockLevel);
            return first;
        }

        void TogglePerks() {
            if (perkPanel != null)
                perkPanel.Toggle();
        }

        void OnLoadoutRequested(string[] loadout) {
            RefreshPerksChip();
            LoadoutRequested?.Invoke(loadout);
        }

        void PressAbility() {
            if (abilityState == DI_AbilityState.Ready)
                AbilityPressed?.Invoke();
        }

        void SetAbility(DI_AbilityState state, float seconds) {
            if (ability == null)
                return;
            DI_AbilityState previous = abilityState;
            abilityState = state;
            if (state == DI_AbilityState.None) {
                if (ability.Visible)
                    ability.Hide();
                return;
            }
            if (!ability.Visible)
                ability.Show();
            int whole = Mathf.CeilToInt(seconds);
            (string text, Color color) = state switch {
                DI_AbilityState.Locked => (string.Format(abilityLockedFormat, whole), abilityIdleColor),
                DI_AbilityState.Ready => (abilityReadyText, abilityReadyColor),
                DI_AbilityState.Active => (string.Format(abilityActiveFormat, whole), abilityActiveColor),
                _ => (abilitySpentText, abilityIdleColor),
            };
            abilityLabel.text = text;
            abilityKey.color = color;
            if (abilityButton != null)
                abilityButton.interactable = state == DI_AbilityState.Ready;
            if (state == DI_AbilityState.Ready && previous != DI_AbilityState.Ready)
                Punch.Scale(ability.transform, abilityReadyPunch, abilityReadyPunchSeconds);
        }

        void QueueRankUp(in DI_MatchSummary summary) {
            if (!summary.rated || summary.ratingAfter <= summary.ratingBefore)
                return;
            DI_Rank before = DI_Ranks.Of(summary.ratingBefore), after = DI_Ranks.Of(summary.ratingAfter);
            if (after.Index <= before.Index)
                return;
            pendingRank = after;
            rankUpAt = Time.unscaledTime + rankUpDelay;
        }

        void CelebrateRankUp(DI_Rank reached) {
            GameSfx.Play(SfxCue.LevelUp);
            ScreenFx.ShowText(string.Format(rankUpFormat, reached.Name.ToUpperInvariant()), reached.Color, rankUpTextSeconds, rankUpTextSize);
            if (rank != null)
                Punch.Scale(rank.transform, rankUpPunch, rankUpPunchSeconds);
        }

        /// <summary>Adds where the player finished, their rating change and saved stats under the outcome.</summary>
        string WithProgress(string outcome, DI_MatchSummary summary) {
            string text = outcome;
            if (summary.teamCount > 0 && summary.placement > 0)
                text += $"\nFinished {DI_Rating.Ordinal(summary.placement)} of {summary.teamCount}  ·  {RatingText(summary)}";
            if (summary.saved)
                text += $"\nBases captured {summary.matchCaptures} (all time {summary.totalCaptures})  ·  " +
                        $"Most held {summary.matchMostHeld} (best {summary.bestMostHeld})" +
                        (summary.matchBounties > 0 ? $"\nBounties claimed {summary.matchBounties} (all time {summary.totalBounties})" : string.Empty);
            return text;
        }

        string RatingText(in DI_MatchSummary summary) {
            if (!summary.rated)
                return string.IsNullOrEmpty(summary.unratedReason) ? "Unrated" : $"Unrated: {summary.unratedReason}";
            int delta = summary.ratingAfter - summary.ratingBefore;
            DI_Rank rankAfter = DI_Ranks.Of(summary.ratingAfter);
            string color = ColorUtility.ToHtmlStringRGB(delta >= 0 ? ratingGainColor : ratingLossColor);
            return $"Rating {summary.ratingAfter} <color=#{color}>({delta:+0;-0;+0})</color>  ·  {rankAfter.Name}";
        }
    }
}
