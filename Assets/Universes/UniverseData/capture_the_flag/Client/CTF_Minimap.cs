using System.Collections.Generic;
using FishNet;
using FishNet.Managing.Client;
using FishNet.Transporting;
using RyanAssets.Characters.Client;
using RyanAssets.UI.GameHud;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

namespace Universes.UniverseData.capture_the_flag.Client {
    /// <summary>
    /// The tactical map on the left: the arena from above (your base on the left), both flags where
    /// they are now, the power-ups, you and your teammates. Enemies show only when the game gives them
    /// away: while carrying your flag, for a moment after they shoot, the one who just killed you, and
    /// all of them during your team's radar sweep. Reads <see cref="CTF_ClientController"/> and the
    /// hit/kill broadcasts; decides nothing.
    /// </summary>
    public sealed class CTF_Minimap : MonoBehaviour {
        [Header("Parts (generated by CTF_HudAuthoring)")]
        public CTF_ClientController hud;
        public HudPopup panel;
        [Tooltip("The map area: markers are placed in it, centred, in its own pixels.")]
        public RectTransform area;
        [Tooltip("The arena render; turned half a circle for Blue.")]
        public RectTransform background;
        [Tooltip("A ring that sweeps out from the centre while your team's radar runs.")]
        public Image sweepRing;
        [Tooltip("\"RADAR 6s\" while your team's sweep runs.")]
        public TMP_Text radarLabel;
        [Tooltip("The arena on the ground plane (x = world x, y = world z): CTF_ArenaAuthoring.FieldRect.")]
        public Rect field = Rect.MinMaxRect(-120f, -72f, 120f, 72f);

        [Header("Icons")]
        public Sprite dotSprite;
        public Sprite arrowSprite, flagSprite, killerSprite;
        [Tooltip("Power-up icons in CTF_PowerUpKind order.")]
        public Sprite[] powerUpSprites = new Sprite[0];
        [Tooltip("Power-up colours in CTF_PowerUpKind order.")]
        public Color[] powerUpColors = new Color[0];

        [Header("Look (pixels on the map)")]
        [Min(2f)] public float selfSize = 22f;
        [Min(2f)] public float mateSize = 11f;
        [Min(2f)] public float enemySize = 12f;
        [Min(2f)] public float flagSize = 22f;
        [Min(2f)] public float killerSize = 22f;
        [Min(2f)] public float powerUpSize = 15f;
        [Range(0f, 1f)] public float spentPowerUpAlpha = 0.25f;
        [Tooltip("A carried or dropped flag pulses this much bigger, this many times a second.")]
        [Range(0f, 1f)] public float flagPulse = 0.35f;
        [Min(0.1f)] public float flagPulsesPerSecond = 2.2f;

        [Header("Spotting")]
        [Tooltip("Seconds an enemy shows after they land a hit on anyone.")]
        [Min(0f)] public float shotSpotSeconds = 2.5f;
        [Tooltip("Spotted enemies fade out over this many seconds at the end.")]
        [Min(0f)] public float spotFadeSeconds = 0.6f;
        [Tooltip("Seconds one radar ring takes to cross the map.")]
        [Min(0.2f)] public float sweepSeconds = 1.4f;

        ClientManager manager;
        readonly List<Image> pool = new();
        readonly Dictionary<int, float> spottedUntil = new();
        readonly float[] radarUntil = new float[2];
        int used, killerId = -1, shownRadarSeconds = -1;
        float killerUntil;
        CTF_Team killerTeam;
        bool flipped, flipKnown;

        int MyId => manager != null && manager.Connection != null ? manager.Connection.ClientId : -1;

        /// <summary>A radar power-up was taken by <paramref name="team"/>: its players see every enemy for <paramref name="seconds"/>.</summary>
        public void Sweep(CTF_Team team, float seconds) =>
            radarUntil[(int)team] = CTF_MapMath.Spot(radarUntil[(int)team], Time.time, seconds);

        /// <summary>Your team's radar sweep is running.</summary>
        public bool RadarOn => hud != null && hud.HasTeam && Time.time < radarUntil[(int)hud.MyTeam];

        void OnDestroy() {
            if (manager == null) return;
            manager.UnregisterBroadcast<CTF_HitBroadcast>(OnHit);
            manager.UnregisterBroadcast<CTF_KillBroadcast>(OnKill);
        }

        void Update() {
            if (manager == null && InstanceFinder.ClientManager != null) {
                manager = InstanceFinder.ClientManager;
                manager.RegisterBroadcast<CTF_HitBroadcast>(OnHit);
                manager.RegisterBroadcast<CTF_KillBroadcast>(OnKill);
            }
            bool show = ShouldShow();
            if (show != panel.Visible) {
                if (show) panel.Show();
                else panel.Hide();
            }
            if (!show) return;
            Orient();
            used = 0;
            DrawPowerUps();
            DrawPeople();
            DrawFlag(CTF_Team.Red);
            DrawFlag(CTF_Team.Blue);
            DrawKiller();
            DrawSelf();
            for (int i = used; i < pool.Count; i++)
                if (pool[i].enabled) pool[i].enabled = false;
            DrawRadar();
        }

        /// <summary>During play and the countdown, except while the summary card or the challenges panel (J) has the left column.</summary>
        bool ShouldShow() {
            if (hud == null || !hud.HasState || !hud.HasTeam) return false;
            if (hud.Phase is not (CTF_Phase.Playing or CTF_Phase.Countdown)) return false;
            if (hud.SummaryShowing) return false;
            var retention = hud.Retention;
            return retention == null || (!retention.ChallengesOpen && !retention.Hidden);
        }

        /// <summary>Blue sees the map turned half a circle, so its own base is on the left too.</summary>
        void Orient() {
            bool flip = CTF_MapMath.Flipped(hud.MyTeam);
            if (flipKnown && flip == flipped) return;
            flipKnown = true;
            flipped = flip;
            if (background != null) background.localEulerAngles = new Vector3(0f, 0f, flip ? 180f : 0f);
        }

        // ---------------------------------------------------------------- layers (drawn bottom to top)
        void DrawPowerUps() {
            var spots = hud.Map != null ? hud.Map.powerUps : null;
            if (spots == null) return;
            foreach (var spot in spots) {
                if (spot == null) continue;
                int kind = (int)spot.kind;
                Sprite sprite = kind < powerUpSprites.Length ? powerUpSprites[kind] : dotSprite;
                Color color = kind < powerUpColors.Length ? powerUpColors[kind] : Color.white;
                color.a = spot.Available ? 1f : spentPowerUpAlpha;
                Place(sprite, color, spot.Position, powerUpSize, 0f);
            }
        }

        void DrawPeople() {
            var roster = hud.Roster;
            int me = MyId;
            CTF_Team mine = hud.MyTeam;
            var enemyFlag = hud.FlagSnap(mine);
            bool radar = RadarOn;
            DrawList(roster.players, me, mine, enemyFlag, radar);
            DrawList(roster.bots, me, mine, enemyFlag, radar);
        }

        void DrawList(CTF_BotView[] list, int me, CTF_Team mine, CTF_FlagSnap ourFlag, bool radar) {
            if (list == null) return;
            float now = Time.time;
            foreach (var view in list) {
                if (!view.alive || view.actorId == me) continue;
                Transform body = hud.ActorBody(view.actorId);
                if (body == null) continue;
                Color color = CTF_Rules.Color(view.team);
                if (view.team == mine) {
                    Place(dotSprite, color, body.position, mateSize, 0f);
                    continue;
                }
                bool carrier = ourFlag.state == CTF_FlagState.Carried && ourFlag.carrierId == view.actorId;
                // Your killer gets its own marker over the flags (DrawKiller).
                if (view.actorId == killerId && now < killerUntil) continue;
                float spot = CTF_MapMath.SpotAlpha(now, spottedUntil.TryGetValue(view.actorId, out float until) ? until : 0f, spotFadeSeconds);
                if (!CTF_MapMath.EnemyShown(carrier, radar, spot)) continue;
                color.a = carrier || radar ? 1f : spot;
                Place(dotSprite, color, body.position, enemySize, 0f);
            }
        }

        void DrawFlag(CTF_Team team) {
            var snap = hud.FlagSnap(team);
            float size = flagSize;
            if (snap.state != CTF_FlagState.Home)
                size *= 1f + flagPulse * (0.5f + 0.5f * Mathf.Sin(Time.unscaledTime * flagPulsesPerSecond * Mathf.PI * 2f));
            Place(flagSprite, CTF_Rules.Color(team), hud.FlagShown(team), size, 0f);
        }

        /// <summary>Whoever eliminated you: a white skull on a disc of their colour, above everything but you, until you are back.</summary>
        void DrawKiller() {
            if (killerId < 0 || Time.time >= killerUntil) return;
            Transform body = hud.ActorBody(killerId);
            if (body == null) return;
            Place(dotSprite, CTF_Rules.Color(killerTeam), body.position, killerSize, 0f);
            Place(killerSprite, Color.white, body.position, killerSize * 0.7f, 0f);
        }

        void DrawSelf() {
            var me = LocalPlayer.Character;
            if (me == null) return;
            Camera view = Camera.main;
            Vector3 forward = view != null ? view.transform.forward : me.transform.forward;
            Place(arrowSprite, Color.white, me.transform.position, selfSize, CTF_MapMath.ArrowDegrees(forward, flipped));
        }

        /// <summary>The sweep ring and the seconds left while your team's radar runs.</summary>
        void DrawRadar() {
            float left = hud.HasTeam ? radarUntil[(int)hud.MyTeam] - Time.time : 0f;
            bool on = left > 0f;
            if (sweepRing != null) {
                if (sweepRing.enabled != on) sweepRing.enabled = on;
                if (on) {
                    float t = Mathf.Repeat(Time.unscaledTime / sweepSeconds, 1f);
                    float span = Mathf.Max(area.rect.width, area.rect.height) * 1.2f;
                    sweepRing.rectTransform.sizeDelta = Vector2.one * Mathf.Lerp(8f, span, t);
                    var c = sweepRing.color;
                    c.a = 0.85f * (1f - t);
                    sweepRing.color = c;
                }
            }
            if (radarLabel == null) return;
            int seconds = on ? Mathf.CeilToInt(left) : -1;
            if (seconds == shownRadarSeconds) return;
            shownRadarSeconds = seconds;
            radarLabel.enabled = on;
            if (on) radarLabel.SetText("RADAR {0}s", seconds);
        }

        // ---------------------------------------------------------------- markers
        void Place(Sprite sprite, Color color, Vector3 world, float size, float degrees) {
            Image image = Next();
            if (image.sprite != sprite) image.sprite = sprite;
            image.color = color;
            Vector2 at = CTF_MapMath.ToMap(world, field, flipped);
            Rect rect = area.rect;
            var t = image.rectTransform;
            t.anchoredPosition = new Vector2((at.x - 0.5f) * rect.width, (at.y - 0.5f) * rect.height);
            t.sizeDelta = new Vector2(size, size);
            t.localEulerAngles = new Vector3(0f, 0f, degrees);
        }

        /// <summary>The next pooled marker, made on first use (a dark outline keeps it readable on any ground).</summary>
        Image Next() {
            if (used < pool.Count) {
                var reused = pool[used++];
                if (!reused.enabled) reused.enabled = true;
                return reused;
            }
            var go = new GameObject($"Marker{pool.Count}", typeof(RectTransform), typeof(Image), typeof(Outline));
            var t = (RectTransform)go.transform;
            t.SetParent(area, false);
            t.anchorMin = t.anchorMax = t.pivot = new Vector2(0.5f, 0.5f);
            var image = go.GetComponent<Image>();
            image.raycastTarget = false;
            image.preserveAspect = true;
            var outline = go.GetComponent<Outline>();
            outline.effectColor = new Color(0f, 0f, 0f, 0.7f);
            outline.effectDistance = new Vector2(1f, -1f);
            pool.Add(image);
            used++;
            return image;
        }

        // ---------------------------------------------------------------- broadcasts
        /// <summary>Whoever lands a hit gives their position away for a moment.</summary>
        void OnHit(CTF_HitBroadcast message, Channel channel) {
            if (message.attackerId < 0) return;
            spottedUntil[message.attackerId] = CTF_MapMath.Spot(spottedUntil.TryGetValue(message.attackerId, out float until) ? until : 0f, Time.time, shotSpotSeconds);
        }

        /// <summary>Your killer stays marked until you are back.</summary>
        void OnKill(CTF_KillBroadcast message, Channel channel) {
            if (message.victimId == MyId) {
                killerId = message.killerId;
                killerTeam = message.killerTeam;
                killerUntil = Time.time + message.respawnSeconds;
            } else if (message.victimId == killerId) {
                killerId = -1;
            }
        }
    }
}
