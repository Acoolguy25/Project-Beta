        void FindRetention() {
            if (retentionHud == null) retentionHud = GetComponentInChildren<RetentionHud>(true);
            if (summaryCard == null && retentionHud != null) summaryCard = retentionHud.GetComponentInChildren<RetentionSummaryCard>(true);
