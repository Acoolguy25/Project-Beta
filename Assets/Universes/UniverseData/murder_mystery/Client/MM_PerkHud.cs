using RyanAssets.UI.GameHud;
using TMPro;
using UnityEngine;
using UnityEngine.InputSystem;
using UnityEngine.UI;

namespace Universes.UniverseData.murder_mystery.Client {
    /// <summary>
    /// Murder mystery perks on the client (<see cref="MM_Perks"/>): the picker card between rounds (G steps the
    /// murderer perk, H the innocent perk, Shift steps back), the chip that shows the perk in play during a
    /// round, a "NEW PERK" notice when rounds unlock one, and the two perks that need presentation: the
    /// Sixth Sense ping (markers over everyone for a moment, through walls) and the Heartbeat (a beat and a red
    /// edge that quicken as a murderer with the knife out comes closer). The server decides and saves every
    /// pick; this only asks (<see cref="MM_PerkRequest"/>) and draws the answers.
    /// Lives on the MM_HUD prefab next to <see cref="MM_ClientHUD"/> (generated by MM_Authoring).
    /// </summary>
    public sealed class MM_PerkHud : MonoBehaviour {
        [Header("Picker (between rounds)")]
        public HudPopup card;
        public Image murdererIcon, innocentIcon;
        public TMP_Text murdererName, murdererNote, innocentName, innocentNote;
        [Tooltip("Icon per perk, in MM_Perk order (baked by the HUD authoring).")]
        public Sprite[] perkIcons = new Sprite[0];
        [SerializeField] InputAction murdererPerkInput = new("MurdererPerk", InputActionType.Button, "<Keyboard>/g");
        [SerializeField] InputAction innocentPerkInput = new("InnocentPerk", InputActionType.Button, "<Keyboard>/h");
        [Min(0f)] public float changePunch = 0.15f;
        [Tooltip("Centre notice for a pick or a locked key: seconds up and size (1 = the countdown's size).")]
        [Min(0.2f)] public float noticeSeconds = 1.8f;
        [Range(0.1f, 1f)] public float noticeSize = 0.32f;
        [Min(0.2f)] public float newPerkSeconds = 3f;
        public Color lockedColor = new(0.62f, 0.66f, 0.72f);

        [Header("Perk in play (during the hunt)")]
        public HudChip activeChip;

        [Header("Sixth Sense")]
        [Tooltip("One marker, cloned for each character a ping shows (authored in the HUD).")]
        public RectTransform senseMarkerTemplate;
        [Tooltip("The markers stand this high above a character's feet (the robots are about 5.6 m tall).")]
        [Min(0f)] public float senseMarkerHeight = 3f;
        [Tooltip("A marker pops in at this scale and settles to 1.")]
        [Min(1f)] public float senseMarkerPopScale = 1.6f;
        [Tooltip("Someone off screen gets a marker pinned this far inside the screen edge (pixels), drawn at Sense Edge Scale.")]
        [Min(0f)] public float senseEdgeMargin = 48f;
        [Range(0.2f, 1f)] public float senseEdgeScale = 0.7f;
        public Color senseFlash = new(0.95f, 0.3f, 0.3f, 0.18f);
        [Min(0f)] public float senseFlashSeconds = 0.4f;
        public SfxSound senseSound = new();

        [Header("Heartbeat")]
        public SfxSound heartbeatSound = new();
        [Tooltip("Beats per minute with a murderer at the edge of the range and right there.")]
        public Vector2 beatsPerMinute = new(66f, 150f);
        public Vector2 beatVolume = new(0.3f, 1f);
        [Tooltip("Seconds the felt danger takes to follow the server's reading, so it swells and fades.")]
        [Min(0.01f)] public float heartbeatSmoothing = 0.5f;
        public Color heartbeatVignette = new(0.6f, 0.02f, 0.05f, 1f);
        [Range(0f, 1f)] public float heartbeatVignetteAlpha = 0.32f;

        ClientManager manager;
        MM_PerksBroadcast perks;
        bool hasPerks;
        MM_StateBroadcast state;
        bool hasState;
        // What the active chip shows, so a steady hunt builds no strings.
        MM_Perk chipPerk = (MM_Perk)255;
        int chipSeconds = -1;
        float heartbeat, sinceBeat, sentStrength = -1f;

        sealed class Marker {
            public RectTransform rect;
            public CanvasGroup group;
            public Vector3 world;
            public float shownAt, until;
        }

        readonly List<Marker> markers = new();
        float senseStartedAt, senseUntil;

        void Awake() {
            card.HideImmediate();
            activeChip.SetVisible(false);
            senseMarkerTemplate.gameObject.SetActive(false);
        }

        void OnEnable() {
            murdererPerkInput.Enable();
            innocentPerkInput.Enable();
        }

        void OnDisable() {
            murdererPerkInput.Disable();
            innocentPerkInput.Disable();
            HideMarkers();
            StopHeartbeat();
        }

        void OnDestroy() {
            if (manager == null)
                return;
            manager.UnregisterBroadcast<MM_PerksBroadcast>(OnPerks);
            manager.UnregisterBroadcast<MM_StateBroadcast>(OnState);
            manager.UnregisterBroadcast<MM_SensePingBroadcast>(OnSensePing);
        }

        void Update() {
            if (manager == null && InstanceFinder.ClientManager != null) {
                manager = InstanceFinder.ClientManager;
                manager.RegisterBroadcast<MM_PerksBroadcast>(OnPerks);
                manager.RegisterBroadcast<MM_StateBroadcast>(OnState);
                manager.RegisterBroadcast<MM_SensePingBroadcast>(OnSensePing);
            }
            bool classic = hasState && state.classic;
            bool hunting = classic && state.phase == MM_Phase.Hunt;
            card.SetVisible(classic && hasPerks && !hunting);
            ReadKeys(classic);
            RefreshActiveChip(hunting);
            TickMarkers();
            TickHeartbeat(hunting);
        }

        // ---------- picker ----------

        void ReadKeys(bool classic) {
            if (!classic || !hasPerks || manager == null || !manager.Started)
                return;
            // The character map is off while typing in chat or a menu is open.
            if (InputService.Instance != null && !InputService.GetActionMapActive(RyanAssetsActionMap.Character))
                return;
            int step = Back() ? -1 : 1;
            if (murdererPerkInput.WasPressedThisFrame())
                Ask(MM_PerkSlot.Murderer, step);
            if (innocentPerkInput.WasPressedThisFrame())
                Ask(MM_PerkSlot.Innocent, step);
        }

        static bool Back() {
            Keyboard keyboard = Keyboard.current;
            return keyboard != null && (keyboard.leftShiftKey.isPressed || keyboard.rightShiftKey.isPressed);
        }

        void Ask(MM_PerkSlot slot, int step) {
            if (MM_Perks.Count(slot, perks.roundsPlayed).unlocked == 0) {
                // Nothing to pick yet: say what unlocks next instead of a silent key.
                if (MM_Perks.NextLocked(slot, perks.roundsPlayed, out MM_Perks.Definition next))
                    ScreenFx.ShowText($"{next.title} unlocks after {next.unlockRounds} rounds", lockedColor, noticeSeconds, noticeSize);
                GameSfx.Play(SfxCue.Error, 0.5f);
                Punch.Scale(card.transform, changePunch * 0.6f, 0.15f);
                return;
            }
            manager.Broadcast(new MM_PerkRequest { slot = slot, step = step });
        }

        void OnPerks(MM_PerksBroadcast message, Channel channel) {
            int roundsBefore = hasPerks ? perks.roundsPlayed : message.roundsPlayed;
            perks = message;
            hasPerks = true;
            FillSlot(MM_PerkSlot.Murderer, message.murdererPerk, murdererIcon, murdererName, murdererNote);
            FillSlot(MM_PerkSlot.Innocent, message.innocentPerk, innocentIcon, innocentName, innocentNote);

            if (MM_Perks.JustUnlocked(roundsBefore, message.roundsPlayed, out MM_Perks.Definition unlocked)) {
                string slot = unlocked.slot == MM_PerkSlot.Murderer ? "G" : "H";
                ScreenFx.ShowText($"NEW PERK: {unlocked.title.ToUpperInvariant()}\n<size=55%>{unlocked.description}  Press {slot} to pick it.</size>",
                    Color.Lerp(unlocked.color, Color.white, 0.3f), newPerkSeconds, noticeSize);
                GameSfx.Play(SfxCue.LevelUp, 0.8f);
                Punch.Scale(card.transform, changePunch, 0.25f);
            }
            if (!message.changed)
                return;
            MM_Perk picked = message.changedSlot == MM_PerkSlot.Murderer ? message.murdererPerk : message.innocentPerk;
            MM_Perks.Definition definition = MM_Perks.Get(picked);
            Punch.Scale((message.changedSlot == MM_PerkSlot.Murderer ? murdererIcon : innocentIcon).transform, changePunch * 2f, 0.2f);
            GameSfx.Play(SfxCue.UiClick);
            // Changed mid-round: it applies from the next one.
            bool later = hasState && state.classic && state.phase is MM_Phase.RoleReveal or MM_Phase.Hunt;
            string when = later ? "  (from next round)" : "";
            ScreenFx.ShowText($"{definition.title}{when}\n<size=55%>{definition.description}</size>", Color.white, noticeSeconds, noticeSize);
        }

        void FillSlot(MM_PerkSlot slot, MM_Perk perk, Image icon, TMP_Text name, TMP_Text note) {
            MM_Perks.Definition definition = MM_Perks.Get(perk);
            icon.sprite = Icon(perk);
            icon.color = perk == MM_Perk.None ? lockedColor : Color.Lerp(definition.color, Color.white, 0.15f);
            name.text = definition.title;
            (int unlocked, int total) = MM_Perks.Count(slot, perks.roundsPlayed);
            string role = slot == MM_PerkSlot.Murderer ? "As murderer" : "As innocent";
            note.text = MM_Perks.NextLocked(slot, perks.roundsPlayed, out MM_Perks.Definition next)
                ? $"{role} · {unlocked}/{total} · next in {next.unlockRounds - perks.roundsPlayed} rounds"
                : $"{role} · {unlocked}/{total} unlocked";
            note.color = lockedColor;
        }

        Sprite Icon(MM_Perk perk) => perkIcons != null && (int)perk < perkIcons.Length ? perkIcons[(int)perk] : null;

        // ---------- in play ----------

        void OnState(MM_StateBroadcast next, Channel channel) {
            state = next;
            hasState = true;
        }

        /// <summary>During the hunt: the perk in play, with the Sixth Sense countdown.</summary>
        void RefreshActiveChip(bool hunting) {
            bool show = hunting && state.alive && state.perk != MM_Perk.None;
            activeChip.SetVisible(show);
            if (!show)
                return;
            int seconds = state.perk == MM_Perk.SixthSense ? Mathf.CeilToInt(state.senseCooldown) : -1;
            if (state.perk == chipPerk && seconds == chipSeconds)
                return;
            chipPerk = state.perk;
            chipSeconds = seconds;
            MM_Perks.Definition definition = MM_Perks.Get(state.perk);
            activeChip.SetIcon(Icon(state.perk));
            activeChip.SetTint(definition.color);
            activeChip.label.text = seconds > 0 ? $"{definition.title} <color=#9AA3AF>· ping in {seconds}s</color>" : definition.title;
        }

        // ---------- Sixth Sense ----------

        void OnSensePing(MM_SensePingBroadcast ping, Channel channel) {
            float now = Time.unscaledTime;
            senseStartedAt = now;
            senseUntil = now + ping.seconds;
            Vector3[] positions = ping.positions ?? System.Array.Empty<Vector3>();
            for (int i = 0; i < positions.Length; i++) {
                Marker marker = MarkerAt(i);
                marker.world = positions[i] + Vector3.up * senseMarkerHeight;
                marker.shownAt = now + i * 0.03f; // a quick ripple rather than all at once
                marker.until = senseUntil;
            }
            for (int i = positions.Length; i < markers.Count; i++)
                markers[i].until = 0f;
            GameSfx.Play(senseSound);
            ScreenFx.Flash(senseFlash, senseFlashSeconds);
            Punch.Scale(activeChip.transform, changePunch, 0.2f);
        }

        Marker MarkerAt(int index) {
            while (markers.Count <= index) {
                RectTransform rect = Instantiate(senseMarkerTemplate, senseMarkerTemplate.parent);
                rect.name = $"SenseMarker{markers.Count}";
                markers.Add(new Marker { rect = rect, group = rect.GetComponent<CanvasGroup>() });
            }
            return markers[index];
        }

        void TickMarkers() {
            if (markers.Count == 0)
                return;
            float now = Time.unscaledTime;
            Camera cam = now < senseUntil ? Camera.main : null;
            RectTransform area = (RectTransform)senseMarkerTemplate.parent;
            foreach (Marker marker in markers) {
                bool live = cam != null && now >= marker.shownAt && now < marker.until;
                bool edge = false;
                Vector2 local = default;
                if (live) {
                    Vector2 screen = ScreenPoint(cam, marker.world, out edge);
                    // The overlay canvas needs no camera for the conversion.
                    live = RectTransformUtility.ScreenPointToLocalPointInRectangle(area, screen, null, out local);
                }
                if (live)
                    marker.rect.anchoredPosition = local;
                if (marker.rect.gameObject.activeSelf != live)
                    marker.rect.gameObject.SetActive(live);
                if (!live)
                    continue;
                float age = now - marker.shownAt, life = Mathf.Max(0.01f, marker.until - marker.shownAt);
                float pop = Mathf.Clamp01(age / 0.18f);
                marker.rect.localScale = Vector3.one * (Mathf.Lerp(senseMarkerPopScale, 1f, pop) * (edge ? senseEdgeScale : 1f));
                // Holds, then fades over the last third.
                marker.group.alpha = Mathf.Clamp01(3f * (1f - age / life)) * pop;
            }
        }

        /// <summary>
        /// Where a marker goes on screen. Someone off screen (or behind the camera) is pinned to the nearest edge
        /// in their direction, so the ping always says which way everyone is.
        /// </summary>
        Vector2 ScreenPoint(Camera cam, Vector3 world, out bool edge) {
            Vector3 point = cam.WorldToScreenPoint(world);
            Vector2 centre = new(Screen.width * 0.5f, Screen.height * 0.5f);
            Vector2 offset = (Vector2)point - centre;
            if (point.z < 0f)
                offset = -offset; // behind: the projection is mirrored
            if (point.z < 0f && offset.sqrMagnitude < 1f)
                offset = Vector2.down; // straight behind: the bottom edge
            Vector2 half = Vector2.Max(Vector2.one, centre - Vector2.one * senseEdgeMargin);
            // How far past the inner rectangle the point is (1 = on its edge).
            float reach = Mathf.Max(Mathf.Abs(offset.x) / half.x, Mathf.Abs(offset.y) / half.y);
            edge = point.z < 0f || reach > 1f;
            return edge ? centre + offset / reach : centre + offset;
        }

        void HideMarkers() {
            senseUntil = 0f;
            foreach (Marker marker in markers)
                if (marker.rect != null)
                    marker.rect.gameObject.SetActive(false);
        }

        // ---------- Heartbeat ----------

        void TickHeartbeat(bool hunting) {
            float target = hunting && state.alive && state.perk == MM_Perk.Heartbeat && LocalPlayer.Character != null ? state.heartbeat / 255f : 0f;
            float dt = Time.unscaledDeltaTime;
            heartbeat = Mathf.MoveTowards(heartbeat, target, dt / heartbeatSmoothing);
            float bpm = Mathf.Lerp(beatsPerMinute.x, beatsPerMinute.y, heartbeat);
            if (heartbeat > 0.01f) {
                sinceBeat += dt;
                if (sinceBeat >= 60f / bpm) {
                    sinceBeat = 0f;
                    GameSfx.Play(heartbeatSound, Mathf.Lerp(beatVolume.x, beatVolume.y, heartbeat));
                }
            } else {
                sinceBeat = 0f;
            }
            float strength = heartbeat > 0.01f ? heartbeat : 0f;
            // Only tell the overlay when it changes noticeably.
            if (Mathf.Abs(strength - sentStrength) > 0.02f || (strength == 0f) != (sentStrength == 0f)) {
                sentStrength = strength;
                ScreenFx.SetDanger(strength, heartbeatVignette, heartbeatVignetteAlpha, bpm / 60f);
            }
        }

        void StopHeartbeat() {
            heartbeat = 0f;
            if (sentStrength > 0f)
                ScreenFx.ClearDanger();
            sentStrength = -1f;
        }
    }
}
