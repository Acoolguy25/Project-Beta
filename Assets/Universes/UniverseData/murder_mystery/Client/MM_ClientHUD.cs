        void OnDestroy() {
            if (gunGlow != null)
                Destroy(gunGlow);
            if (manager == null)
                return;
            manager.UnregisterBroadcast<MM_StateBroadcast>(OnState);
            manager.UnregisterBroadcast<MM_ResultsBroadcast>(OnResults);
            manager.UnregisterBroadcast<MM_KillBroadcast>(OnKill);
            manager.UnregisterBroadcast<MM_CoinBroadcast>(OnCoin);
            manager.UnregisterBroadcast<MM_AnnounceBroadcast>(OnAnnounce);
        }

        void Update() {
            if (manager == null && InstanceFinder.ClientManager != null) {
                manager = InstanceFinder.ClientManager;
                manager.RegisterBroadcast<MM_StateBroadcast>(OnState);
                manager.RegisterBroadcast<MM_ResultsBroadcast>(OnResults);
                manager.RegisterBroadcast<MM_KillBroadcast>(OnKill);
                manager.RegisterBroadcast<MM_CoinBroadcast>(OnCoin);
                manager.RegisterBroadcast<MM_AnnounceBroadcast>(OnAnnounce);
            }
            Refresh();
        }

        bool Classic => hasState && state.classic;
        bool Hunting => Classic && state.phase == MM_Phase.Hunt;

        // ---------- network ----------

        void OnState(MM_StateBroadcast next, Channel channel) {
            state = next;
            hasState = true;
            if (!next.classic) {
                ApplyState();
                return;
            }

            if (next.phase == MM_Phase.RoleReveal && revealShownRound != next.round && next.role != MM_Role.None) {
                revealShownRound = next.round;
                revealIsHero = false;
                revealUntil = Time.unscaledTime + Mathf.Max(3, next.secondsLeft);
            }
            // Picking up the dead sheriff's gun gets its own card at the top of the screen.
            if (next.phase == MM_Phase.Hunt && next.alive && next.hero && (!wasHero || heroRound != next.round)) {
                revealIsHero = true;
                revealUntil = Time.unscaledTime + heroRevealSeconds;
                announcement.Hide();
            }
            wasHero = next.hero;
            heroRound = next.round;
            if (next.phase is MM_Phase.RoleReveal or MM_Phase.Hunt && next.role != MM_Role.None) {
                playedRole = next.role;
                playedRound = next.round;
            }

            float knifeCooldown = Mathf.Max(next.killCooldown, next.throwCooldown);
            if (next.phase == MM_Phase.Hunt && next.role == MM_Role.Murderer && next.alive && lastKnifeCooldown > 0f && knifeCooldown <= 0f) {
                GameSfx.Play(SfxCue.CountdownBeep, knifeReadyBeepVolume);
                Punch.Scale(roleChip.transform);
            }
            lastKnifeCooldown = knifeCooldown;

            // The last seconds of the hunt count down out loud.
            if (next.phase == MM_Phase.Hunt && next.secondsLeft > 0 && next.secondsLeft <= finalCountdownSeconds && next.secondsLeft != lastBeepSecond) {
                lastBeepSecond = next.secondsLeft;
                GameSfx.Play(SfxCue.CountdownBeep, countdownVolume, next.secondsLeft <= 3 ? GameSfx.Semitones(5f) : 1f);
            }

            UpdateGunBeacon();
            ApplyState();
        }

        void OnKill(MM_KillBroadcast kill, Channel channel) {
            Vector3 at = kill.position + Vector3.up * killFxHeight;
            GameFx.Play(FxKind.Sparks, at, killSparkColor, killFxScale);
            if (killRingScale > 0f)
                GameFx.Play(FxKind.ShockwaveRing, kill.position, killSparkColor, killRingScale);
            GameSfx.PlayAt(SfxCue.Kill, kill.position);
            if (!kill.byGun)
                GameSfx.PlayAt(killSting, kill.position);
            if (kill.youDied) {
                ScreenFx.Flash(deathFlash, deathFlashSeconds);
                CameraShake.Kick(deathKickStrength, deathKickSeconds);
                ScreenFx.ShowText("YOU WERE KILLED", Alarm, deathTextSeconds);
            } else {
                float strength = kill.youKilled ? killShakeStrength * killerShakeMultiplier : killShakeStrength;
                CameraShake.Explosion(kill.position, killShakeRadius, strength, killShakeSeconds);
            }
        }

        void OnCoin(MM_CoinBroadcast coin, Channel channel) {
            coinLadder.Play(coinVolume);
            if (coinBurstScale > 0f)
                GameFx.Play(FxKind.CoinBurst, coin.position, coinBurstScale);
            FloatingText.Spawn(coin.position + Vector3.up * coinTextHeight, "+1", Gold, coinTextSize);
            state.coins = coin.coins;
            state.coinCap = coin.coinCap;
            SetCoinChip();
            Punch.Scale(coinChip.transform, coinPunchScale, coinPunchSeconds);
            if (coin.coinCap > 0 && coin.coins >= coin.coinCap) {
                GameSfx.Play(SfxCue.Pickup);
                ScreenFx.ShowText("BAG FULL", Gold, bagFullTextSeconds);
            }
        }

        void OnAnnounce(MM_AnnounceBroadcast message, Channel channel) {
            if (!Classic)
                return;
            bool alive = state.alive;
            bool murderer = state.role == MM_Role.Murderer;
            float now = Time.unscaledTime;
            switch (message.kind) {
                case MM_Announcement.GunDropped:
                    GameSfx.Play(gunDroppedSound);
                    GameSfx.Play(SfxCue.Alarm, gunDroppedAlarmVolume);
                    ScreenFx.Flash(WithAlpha(MM_Text.RoleColor(MM_Role.Sheriff), gunDroppedFlashAlpha), gunDroppedFlashSeconds);
                    CameraShake.Kick(gunDroppedKickStrength, gunDroppedKickSeconds);
                    string grab = murderer ? "Their gun is on the floor. Don't let anyone take it."
                        : alive ? "Their gun is on the floor. Grab it and become the hero!"
                        : "Their gun is on the floor. Will anyone grab it?";
                    // The sheriff falling right after shooting an innocent continues that story.
                    if (shownAnnouncement == MM_Announcement.SheriffMistake && now - shownAnnouncementAt <= mistakeMergeSeconds && announcement.Visible) {
                        announcement.Set(mistakeIcon, Alarm, "THE SHERIFF SHOT AN INNOCENT", "And paid for it. " + grab);
                        return;
                    }
                    Announce(message.kind, gunIcon, MM_Text.RoleColor(MM_Role.Sheriff), "THE SHERIFF IS DOWN", grab);
                    break;
                case MM_Announcement.GunTaken:
                    // The hero sees their own card instead.
                    if (state.hero)
                        return;
                    GameSfx.Play(SfxCue.Pickup);
                    Announce(message.kind, heroIcon, MM_Text.HeroColor, "SOMEONE TOOK THE GUN",
                        murderer ? "A hero is hunting you now. Watch your back." : "A hero has risen. Stay close to them.");
                    break;
                case MM_Announcement.LastSurvivor:
                    GameSfx.Play(SfxCue.Alarm, lastSurvivorAlarmVolume);
                    bool itsYou = alive && !murderer;
                    Announce(message.kind, survivorIcon, Amber, "ONE SURVIVOR LEFT",
                        itsYou ? "It's you. Hide and hold out until the clock runs out!"
                        : murderer ? "One left. Finish the job." : "Can they hold out?");
                    break;
                case MM_Announcement.SheriffMistake:
                    GameSfx.Play(SfxCue.Lose, sheriffMistakeVolume);
                    Announce(message.kind, mistakeIcon, Alarm, "THE SHERIFF SHOT AN INNOCENT", "And paid for it.");
                    break;
                case MM_Announcement.PlayersOut:
                    Announce(message.kind, endgameIcon, Muted, "NO PLAYERS LEFT", "The townsfolk settle it. Next round soon.");
                    break;
            }
        }

        void Announce(MM_Announcement kind, Sprite icon, Color color, string title, string subtitle) {
            shownAnnouncement = kind;
            shownAnnouncementAt = Time.unscaledTime;
            announcement.Show(icon, color, title, subtitle, announcementSeconds);
        }

        /// <summary>The reveal arrives once per round; the top bar counts down to the next one.</summary>
        void OnResults(MM_ResultsBroadcast next, Channel channel) {
            lastResults = next;
            resultsUntil = Time.unscaledTime + next.secondsLeft + 0.5f;
            if (resultsShownRound != next.round) {
                resultsShownRound = next.round;
                FillResults();
                PlayResultsMoment();
            }
        }

        /// <summary>E: a murderer holding the knife throws it at whatever the cursor points at.</summary>
        void TryThrow() {
            if (manager == null || !manager.Started || !Hunting || state.role != MM_Role.Murderer || !state.alive)
                return;
            if (!HoldingKnife() || KnifeCooldown() > 0f || Time.unscaledTime < throwBlockedUntil)
                return;
            manager.Broadcast(new MM_ThrowKnifeRequest { target = AimPoint() });
            throwBlockedUntil = Time.unscaledTime + throwRequestGuardSeconds;
            Punch.Scale(throwPrompt.transform);
        }

        Vector3 AimPoint() {
            if (ToolControls.TryGetCursorWorldPosition(out Vector3 point))
                return point;
            Camera camera = Camera.main;
            return camera != null ? ToolControls.GetAimRay(camera).GetPoint(throwAimFallbackDistance) : ToolControls.GetCursorWorldPosition();
        }

        static bool HoldingKnife() {
            LocalCharacter character = LocalPlayer.Character;
            return character != null && !character.IsDead && character.ActiveTool.Value != null
                && character.ActiveTool.Value.toolEnum == ToolEnum.Dagger;
        }

        /// <summary>Seconds until the knife may be thrown: the throw cooldown or the kill clock, whichever is longer.</summary>
        float KnifeCooldown() => Mathf.Max(state.killCooldown, state.throwCooldown);

