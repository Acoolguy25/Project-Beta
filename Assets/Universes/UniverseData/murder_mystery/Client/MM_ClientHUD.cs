        int lastRoleRound = -1;
        int lastKillCooldown;
        bool gunOnFloor;
        Vector3 gunPosition;
        FxHandle gunBeacon;
        Coroutine drumroll, gavel;
        readonly List<GameObject> markers = new();

        void Awake() {
            roleReveal.Popup.HideImmediate();
            roleChip.HideImmediate();
            reportPrompt.HideImmediate();
            meetingCard.HideImmediate();
            ejection.Popup.HideImmediate();
            results.HideImmediate();
        }

        void OnEnable() {
            ToolControls.interactPressed += TryReport;
            MoodVolume.Apply(mood, moodFadeSeconds);
        }

        void OnDisable() {
            ToolControls.interactPressed -= TryReport;
            MoodVolume.Clear(moodFadeSeconds);
            gunBeacon.Stop();
            gunOnFloor = false;
            StopDrumroll();
            if (gavel != null) {
                StopCoroutine(gavel);
                gavel = null;
            }
        }

        void OnDestroy() {
            if (manager != null) {
                manager.UnregisterBroadcast<MM_StateBroadcast>(OnState);
                manager.UnregisterBroadcast<MM_MeetingBroadcast>(OnMeeting);
                manager.UnregisterBroadcast<MM_EjectionBroadcast>(OnEjection);
                manager.UnregisterBroadcast<MM_ResultsBroadcast>(OnResults);
                manager.UnregisterBroadcast<MM_KillBroadcast>(OnKill);
            }
            foreach (GameObject marker in markers)
                if (marker != null) Destroy(marker);
        }

        void Update() {
            if (manager == null && InstanceFinder.ClientManager != null) {
                manager = InstanceFinder.ClientManager;
                manager.RegisterBroadcast<MM_StateBroadcast>(OnState);
                manager.RegisterBroadcast<MM_MeetingBroadcast>(OnMeeting);
                manager.RegisterBroadcast<MM_EjectionBroadcast>(OnEjection);
                manager.RegisterBroadcast<MM_ResultsBroadcast>(OnResults);
                manager.RegisterBroadcast<MM_KillBroadcast>(OnKill);
            }
            Refresh();
        }

        // ---------- network ----------

        void OnState(MM_StateBroadcast next, Channel channel) {
            MM_StateBroadcast previous = state;
            bool hadState = hasState;
            state = next;
            hasState = true;
            if (next.classic && next.phase == MM_Phase.RoleReveal && revealShownRound != next.round && next.role != MM_Role.None) {
                revealShownRound = next.round;
                revealIsTakeover = false;
                revealUntil = Time.unscaledTime + Mathf.Max(3, next.secondsLeft);
            }
            // A role taken over mid-round (the dead sheriff's gun, a dropped dagger) gets its own card.
            if (next.classic && next.phase == MM_Phase.Hunt && next.alive && lastRoleRound == next.round
                && lastRole != next.role && next.role is MM_Role.Sheriff or MM_Role.Murderer) {
                revealIsTakeover = true;
                revealUntil = Time.unscaledTime + takeoverRevealSeconds;
            }
            lastRole = next.role;
            lastRoleRound = next.round;
            if (next.phase is not (MM_Phase.Meeting or MM_Phase.Voting))
                hasMeeting = false;

            if (hadState && previous.phase != MM_Phase.Voting && next.phase == MM_Phase.Voting)
                StartDrumroll();
            else if (next.phase != MM_Phase.Voting)
                StopDrumroll();

            if (next.classic && next.role == MM_Role.Murderer && next.alive && lastKillCooldown > 0 && next.killCooldown == 0 && next.phase == MM_Phase.Hunt) {
                GameSfx.Play(SfxCue.CountdownBeep, killReadyBeepVolume);
                Punch.Scale(roleChip.transform);
            }
            lastKillCooldown = next.killCooldown;

            UpdateGunBeacon();
            UpdateMarkers();
            ApplyState();
        }

        void OnMeeting(MM_MeetingBroadcast next, Channel channel) {
            meeting = next;
            hasMeeting = true;
            revealUntil = 0;
            // Body found: alarm, a red flash and a jolt, then the gavel calls the meeting to order.
            GameSfx.Play(SfxCue.Alarm);
            GameSfx.Play(bodyFoundSound);
            ScreenFx.Flash(new Color(Alarm.r, Alarm.g, Alarm.b, meetingFlashAlpha), meetingFlashSeconds);
            CameraShake.Kick(meetingKickStrength, meetingKickSeconds);
            FillMeeting();
            ApplyState();
            if (gavel != null)
                StopCoroutine(gavel);
            gavel = StartCoroutine(KnockGavel());
        }

        void OnEjection(MM_EjectionBroadcast next, Channel channel) {
            ejectionResult = next;
            ejectionUntil = Time.unscaledTime + Mathf.Max(1, next.seconds);
            ejectionShown = false;
            hasMeeting = false;
            StopDrumroll();
            ApplyState();
            // The reveal: a bell, then a flash in the outcome's colour.
            GameSfx.Play(ejectionBell);
            if (!next.ejected)
                return;
            bool caught = next.role == MM_Role.Murderer;
            GameSfx.Play(caught ? SfxCue.Win : SfxCue.Lose);
            Color flash = caught ? MM_Text.RoleColor(MM_Role.Innocent) : Alarm;
            ScreenFx.Flash(new Color(flash.r, flash.g, flash.b, ejectionFlashAlpha), ejectionFlashSeconds);
            CameraShake.Kick(ejectionKickStrength, ejectionKickSeconds);
        }

        void OnKill(MM_KillBroadcast kill, Channel channel) {
            Vector3 at = kill.position + Vector3.up * killFxHeight;
            GameFx.Play(FxKind.Sparks, at, killSparkColor, killFxScale);
            if (killRingScale > 0f)
                GameFx.Play(FxKind.ShockwaveRing, kill.position, killSparkColor, killRingScale);
            GameSfx.PlayAt(SfxCue.Kill, kill.position);
            if (!kill.byGun)
                GameSfx.PlayAt(killSting, kill.position);
            if (kill.youDied) {
                ScreenFx.Flash(deathFlash, deathFlashSeconds);
                CameraShake.Kick(deathKickStrength, deathKickSeconds);
                ScreenFx.ShowText("YOU WERE KILLED", Alarm, deathTextSeconds);
            } else {
                float strength = kill.youKilled ? killShakeStrength * killerShakeMultiplier : killShakeStrength;
                CameraShake.Explosion(kill.position, killShakeRadius, strength, killShakeSeconds);
            }
        }

        void OnResults(MM_ResultsBroadcast next, Channel channel) {
            bool fresh = lastResults.round != next.round || resultsUntil < Time.unscaledTime;
            lastResults = next;
            resultsUntil = Time.unscaledTime + next.secondsLeft + 0.5f;
            if (fresh)
                FillResults();
            resultsTimer.label.SetText("Next round in {0}s", next.secondsLeft);
        }

        void TryReport() {
            if (manager == null || !manager.Started || !hasState || state.reportableBody < 0 || state.phase != MM_Phase.Hunt)
                return;
            if (state.meetingsLeft <= 0 || state.reportCooldown > 0)
                return;
            manager.Broadcast(new MM_ReportRequest { bodyId = state.reportableBody });
        }

        // ---------- presentation ----------

        Sprite RoleIcon(MM_Role role) => role switch {
            MM_Role.Sheriff => sheriffIcon,
            MM_Role.Murderer => murdererIcon,
            MM_Role.Spectator => spectatorIcon,
            _ => innocentIcon,
        };

        /// <summary>
        /// Per frame: only what depends on the clock (the role card's and ejection banner's time on screen,
        /// the results' countdown). Everything driven by the server's state is set in <see cref="ApplyState"/>
        /// when a broadcast arrives, so a steady hunt builds no strings here.
        /// </summary>
        void Refresh() {
            bool classic = hasState && state.classic;
            float now = Time.unscaledTime;

            bool showReveal = classic && now < revealUntil
                && (revealIsTakeover ? state.phase == MM_Phase.Hunt : state.phase == MM_Phase.RoleReveal);
            if (showReveal && !roleReveal.Visible)
                ShowRoleCard();
            else if (!showReveal && roleReveal.Visible)
                roleReveal.Hide();

            bool resultsShowing = lastResults.round == ejectionResult.round && now < resultsUntil;
            bool showEjection = now < ejectionUntil && !resultsShowing;
            if (showEjection && !ejectionShown)
                ShowEjection(now);
            else if (!showEjection && ejection.Visible)
                ejection.Hide();

            results.SetVisible(now < resultsUntil);
        }

        void ShowRoleCard() {
            string title = state.role == MM_Role.Spectator
                ? "You are spectating"
                : revealIsTakeover
                    ? $"You are now the {MM_Text.RoleName(state.role)}"
                    : $"You are {(state.role == MM_Role.Innocent ? "" : "the ")}{MM_Text.RoleName(state.role)}";
            if (roleReveal.kicker != null)
                roleReveal.kicker.text = revealIsTakeover ? TakeoverKicker : RoundStartKicker;
            PlaceRoleCard(revealIsTakeover);
            Color roleColor = MM_Text.RoleColor(state.role);
            roleReveal.Show(RoleIcon(state.role), roleColor, title.ToUpperInvariant(), MM_Text.RoleGoal(state.role), 0f);
            GameSfx.Play(roleRevealSound);
            ScreenFx.Flash(new Color(roleColor.r, roleColor.g, roleColor.b, roleFlashAlpha), roleFlashSeconds);
        }

        Vector2 roleCardCentre;
        bool roleCardCentreKnown;

        /// <summary>Round start: centre, as authored. Takeover: the top slot the meeting card uses.</summary>
        void PlaceRoleCard(bool takeover) {
            RectTransform card = (RectTransform)roleReveal.transform;
            if (!roleCardCentreKnown) {
                roleCardCentre = card.anchoredPosition;
                roleCardCentreKnown = true;
            }
            Vector2 anchor = takeover ? new Vector2(0.5f, 1f) : new Vector2(0.5f, 0.5f);
            card.anchorMin = card.anchorMax = card.pivot = anchor;
            card.anchoredPosition = takeover ? takeoverCardOffset : roleCardCentre;
        }

        void ShowEjection(float now) {
            ejectionShown = true;
            bool murderer = ejectionResult.ejected && ejectionResult.role == MM_Role.Murderer;
            string title = !ejectionResult.ejected ? "NO ONE WAS EJECTED" : murderer ? "MURDERER CAUGHT" : "WRONG PERSON";
            Sprite icon = !ejectionResult.ejected ? nobodyIcon : murderer ? caughtIcon : wrongIcon;
            Color color = !ejectionResult.ejected ? Muted : murderer ? MM_Text.RoleColor(MM_Role.Innocent) : Alarm;
            ejection.Show(icon, color, title, ejectionResult.headline, Mathf.Max(0.5f, ejectionUntil - now));
        }

        // What the role chip's name currently shows (None until the first state).
        MM_Role chipRole;
        bool chipAlive;

        /// <summary>The role chip, kill cooldown, report prompt and meeting card, from the latest server state.</summary>
        void ApplyState() {
            bool classic = hasState && state.classic;

            bool showChip = classic && state.role != MM_Role.None && state.phase is not (MM_Phase.Results or MM_Phase.RoleReveal);
            roleChip.SetVisible(showChip);
            if (showChip) {
                Color color = MM_Text.RoleColor(state.role);
                roleChipDisc.color = state.alive ? color : Color.Lerp(color, Muted, 0.7f);
                roleChipIcon.sprite = state.alive ? RoleIcon(state.role) : diedIcon;
                // The name only changes with the role or a death; the state arrives twice a second.
                if (state.role != chipRole || state.alive != chipAlive) {
                    chipRole = state.role;
                    chipAlive = state.alive;
                    roleChipName.text = state.alive ? MM_Text.RoleName(state.role) : $"{MM_Text.RoleName(state.role)} <size=70%><color=#9AA3AF>· eliminated</color></size>";
                    roleChipName.color = Color.Lerp(color, Color.white, 0.2f);
                }
                meetingsLeft.label.SetText("{0}", state.meetingsLeft);
                meetingsLeft.SetTint(state.meetingsLeft > 0 ? Alarm : Muted);
                meetingsLeft.SetVisible(state.role != MM_Role.Spectator);
            }

            bool showKillCooldown = showChip && state.alive && state.role == MM_Role.Murderer
                && state.phase == MM_Phase.Hunt && state.killCooldown > 0;
            killCooldown.SetVisible(showKillCooldown);
            if (showKillCooldown)
                killCooldown.label.SetText("{0}s", state.killCooldown);

            bool showReport = classic && state.alive && state.phase == MM_Phase.Hunt && state.reportableBody >= 0;
            reportPrompt.SetVisible(showReport);
            if (showReport) {
                bool ready = state.meetingsLeft > 0 && state.reportCooldown <= 0;
                reportKey.color = ready ? Alarm : new Color(0.4f, 0.42f, 0.46f);
                reportText.text = state.meetingsLeft <= 0
                    ? $"Body of <b>{state.reportableBodyName}</b>  <color=#9AA3AF>· no meetings left this round</color>"
                    : state.reportCooldown > 0
                        ? $"Body of <b>{state.reportableBodyName}</b>  <color=#9AA3AF>· report in {state.reportCooldown}s</color>"
                        : $"Report the body of <b>{state.reportableBodyName}</b>";
            }

            // During the vote the shared vote window shows the same details, so the card steps aside.
            bool showMeeting = classic && hasMeeting && state.phase == MM_Phase.Meeting;
            meetingCard.SetVisible(showMeeting);
            if (showMeeting)
                meetingTimer.label.SetText("Voting in {0}s", state.secondsLeft);
        }

        void FillMeeting() {
            meetingBody.text = $"<b>{meeting.reporterName}</b> found the body of <b>{meeting.victimName}</b>.";
            string suspects = meeting.suspects == null || meeting.suspects.Length == 0
                ? "nobody"
                : "<color=#F4F6FA>" + string.Join("</color>,  <color=#F4F6FA>", meeting.suspects) + "</color>";
            meetingSuspects.text = $"Seen nearby:  {suspects}";
        }

        void FillResults() {
            bool murderersWon = lastResults.murderersWon;
            Color color = murderersWon ? Alarm : MM_Text.RoleColor(MM_Role.Innocent);
            resultsTitle.text = (lastResults.winner ?? string.Empty).ToUpperInvariant();
            resultsTitle.color = Color.Lerp(color, Color.white, 0.2f);
            resultsDisc.color = color;
            resultsStripe.color = color;
            resultsSummary.text = lastResults.summary;

            // Murderers, the sheriff and real players first; the crowd of NPC innocents last.
            var entries = new List<MM_ResultEntry>(lastResults.entries ?? System.Array.Empty<MM_ResultEntry>());
            entries.Sort((a, b) => Rank(a).CompareTo(Rank(b)));
            int shown = Mathf.Min(entries.Count, MaxResultRows);
            resultsRows.SetCount(shown);
            for (int i = 0; i < shown; i++) {
                MM_ResultEntry entry = entries[i];
                HudRow row = resultsRows.Row(i);
                Color roleColor = MM_Text.RoleColor(entry.role);
                row.SetIcon(RoleIcon(entry.role), roleColor);
                string who = !entry.isPlayer ? $"{entry.name} <size=80%><color=#7D8796>NPC</color></size>"
                    : string.IsNullOrEmpty(entry.username) ? entry.name
                    : $"{entry.name} <size=80%><color=#9AA3AF>@{entry.username}</color></size>";
                row.Set(0, who);
                row.Set(1, MM_Text.RoleName(entry.role), roleColor);
                (string fate, Color fateColor) = entry.ejected ? ("Ejected", Amber) : entry.survived ? ("Survived", MM_Text.RoleColor(MM_Role.Innocent)) : ("Died", Muted);
                row.Set(2, fate, fateColor);
                row.Set(3, entry.kills > 0 ? entry.kills.ToString() : "-", entry.kills > 0 ? Color.white : Muted);
            }
            int hidden = entries.Count - shown;
            resultsMore.text = hidden > 0 ? $"+ {hidden} more townsfolk" : string.Empty;
            resultsMore.gameObject.SetActive(hidden > 0);
        }

        static int Rank(MM_ResultEntry entry) => entry.role switch {
            MM_Role.Murderer => 0,
            MM_Role.Sheriff => 1,
            _ => entry.isPlayer ? 2 : entry.ejected || entry.kills > 0 ? 3 : 4,
        };

        // ---------- moments ----------

        IEnumerator KnockGavel() {
            yield return new WaitForSecondsRealtime(gavelDelay);
            for (int i = 0; i < gavelKnocks; i++) {
                GameSfx.Play(gavelSound);
                if (meetingCard.Visible)
                    Punch.Scale(meetingCard.transform, gavelPunchScale, gavelPunchSeconds);
                yield return new WaitForSecondsRealtime(gavelSpacing);
            }
            gavel = null;
        }

        void StartDrumroll() {
            StopDrumroll();
            drumroll = StartCoroutine(Drumroll());
        }

        void StopDrumroll() {
            if (drumroll == null)
                return;
            StopCoroutine(drumroll);
            drumroll = null;
        }

        /// <summary>A roll that speeds up and swells while the accusation vote is open; the ejection cuts it off.</summary>
        IEnumerator Drumroll() {
            float started = Time.unscaledTime;
            while (true) {
                float t = Mathf.Clamp01((Time.unscaledTime - started) / drumRampSeconds);
                GameSfx.Play(drumSound, Mathf.Lerp(drumStartVolume, 1f, t));
                yield return new WaitForSecondsRealtime(Mathf.Lerp(drumStartInterval, drumEndInterval, t * t));
            }
        }

        /// <summary>A beam over the dead sheriff's gun while it lies on the floor, for everyone to race to.</summary>
        void UpdateGunBeacon() {
            bool dropped = state.classic && state.gunDropped && state.phase is MM_Phase.Hunt or MM_Phase.Meeting or MM_Phase.Voting or MM_Phase.Ejection;
            if (dropped && !gunOnFloor) {
                gunBeacon = GameFx.Start(FxKind.BeaconBeam, state.gunPosition, MM_Text.RoleColor(MM_Role.Sheriff), gunBeaconScale);
                // The callout invites the living to race for it; the sheriff who just dropped it is reading
                // "YOU WERE KILLED" in the same spot.
                if (state.alive)
                    FloatingText.Callout(state.gunPosition + Vector3.up * gunCalloutHeight, "SHERIFF'S GUN", MM_Text.RoleColor(MM_Role.Sheriff), gunCalloutSize);
                GameSfx.PlayAt(SfxCue.Whoosh, state.gunPosition);
            } else if (dropped && gunPosition != state.gunPosition) {
                gunBeacon.SetPosition(state.gunPosition);
            } else if (!dropped && gunOnFloor) {
                gunBeacon.Stop();
                // Taken (not just a round ending): the pickup is heard where it happened.
                if (state.classic && state.phase == MM_Phase.Hunt)
                    GameSfx.PlayAt(SfxCue.Pickup, gunPosition);
            }
            gunOnFloor = dropped;
            if (dropped)
                gunPosition = state.gunPosition;
        }

        void UpdateMarkers() {
            Vector3[] bodies = hasState && state.classic && state.alive && state.phase == MM_Phase.Hunt && state.nearbyBodies != null
                ? state.nearbyBodies : System.Array.Empty<Vector3>();
            if (bodyMarkerPrefab == null)
                return;
            while (markers.Count < bodies.Length)
                markers.Add(CreateMarker());
            for (int i = 0; i < markers.Count; i++) {
                bool used = i < bodies.Length;
                markers[i].SetActive(used);
                if (used)
                    markers[i].transform.position = bodies[i];
            }
        }

        GameObject CreateMarker() {
            GameObject marker = Instantiate(bodyMarkerPrefab);
            SceneManager.MoveGameObjectToScene(marker, gameObject.scene);
            return marker;
        }
    }
