        Sprite RoleIcon(MM_Role role, bool hero = false) => role switch {
            MM_Role.Sheriff => hero ? heroIcon : sheriffIcon,
            MM_Role.Murderer => murdererIcon,
            MM_Role.Spectator => spectatorIcon,
            _ => innocentIcon,
        };

        /// <summary>
        /// Per frame: what depends on the clock or on the local character (the role card's time on screen,
        /// the throw prompt, which follows the knife being drawn, and the results card). Everything driven by
        /// the server's state is set in <see cref="ApplyState"/> when a broadcast arrives.
        /// </summary>
        void Refresh() {
            float now = Time.unscaledTime;
            bool showReveal = Classic && now < revealUntil
                && (revealIsHero ? state.phase == MM_Phase.Hunt : state.phase == MM_Phase.RoleReveal);
            bool cardStale = cardRound != state.round || cardRole != state.role || cardHero != revealIsHero;
            if (showReveal && (!roleReveal.Visible || cardStale))
                ShowRoleCard();
            else if (!showReveal && roleReveal.Visible)
                roleReveal.Hide();

            RefreshThrowPrompt();
            RefreshDroppedGunDisplay();
            RefreshGunCompass();
            // A new round (a role reveal or a hunt) always clears the last round's card, even if it came early.
            if (hasState && (state.phase == MM_Phase.RoleReveal || state.phase == MM_Phase.Hunt) && state.round > resultsShownRound)
                resultsUntil = 0f;
            results.SetVisible(now < resultsUntil);
            bool betweenRounds = ShowOdds() && now >= resultsUntil;
            oddsChip.SetVisible(betweenRounds);
            skinChip.SetVisible(Classic && hasState && (betweenRounds || state.phase == MM_Phase.RoleReveal));
        }

        // What the throw prompt currently says (so a steady hunt builds no strings).
        int throwPromptMode = -1, throwPromptSeconds = -1;

        void RefreshThrowPrompt() {
            bool show = Hunting && state.role == MM_Role.Murderer && state.alive;
            throwPrompt.SetVisible(show);
            if (!show)
                return;
            int seconds = Mathf.CeilToInt(KnifeCooldown());
            bool holding = HoldingKnife();
            int mode = seconds > 0 ? 0 : holding ? 1 : 2;
            if (mode == throwPromptMode && (mode != 0 || seconds == throwPromptSeconds))
                return;
            throwPromptMode = mode;
            throwPromptSeconds = seconds;
            throwKey.color = mode == 1 ? MM_Text.RoleColor(MM_Role.Murderer) : KeyDisabled;
            if (mode == 0)
                throwText.SetText("Knife ready in {0}s", seconds);
            else
                throwText.text = mode == 1 ? "Throw your knife" : "Throw <color=#9AA3AF>· draw your knife first</color>";
        }

        void ShowRoleCard() {
            MM_Role role = state.role;
            bool hero = revealIsHero;
            cardRound = state.round;
            cardRole = role;
            cardHero = hero;
            string title = role == MM_Role.Spectator ? "You are spectating"
                : hero ? "You are the hero"
                : $"You are {(role == MM_Role.Innocent ? "" : "the ")}{MM_Text.RoleName(role)}";
            string goal = hero ? "Shoot the murderer before they get you. Shoot an innocent and you die too." : MM_Text.RoleGoal(role);
            if (roleReveal.kicker != null)
                roleReveal.kicker.text = hero ? HeroKicker : RoundStartKicker;
            PlaceRoleCard(hero);
            Color color = MM_Text.RoleColor(role, hero);
            roleReveal.Show(RoleIcon(role, hero), color, title.ToUpperInvariant(), goal, 0f);
            GameSfx.Play(roleRevealSound);
            ScreenFx.Flash(WithAlpha(color, roleFlashAlpha), roleFlashSeconds);
        }

        Vector2 roleCardCentre;
        bool roleCardCentreKnown;

        /// <summary>Round start: centre, as authored. Hero: the top slot, clear of your own character.</summary>
        void PlaceRoleCard(bool top) {
            RectTransform card = (RectTransform)roleReveal.transform;
            if (!roleCardCentreKnown) {
                roleCardCentre = card.anchoredPosition;
                roleCardCentreKnown = true;
            }
            Vector2 anchor = top ? new Vector2(0.5f, 1f) : new Vector2(0.5f, 0.5f);
            card.anchorMin = card.anchorMax = card.pivot = anchor;
            card.anchoredPosition = top ? heroCardOffset : roleCardCentre;
        }

        /// <summary>The role chip, coin bag and kill cooldown, and the lobby odds, from the latest server state.</summary>
        void ApplyState() {
            bool showChip = Classic && state.role != MM_Role.None && state.phase == MM_Phase.Hunt;
            roleChip.SetVisible(showChip);
            if (showChip) {
                Color color = MM_Text.RoleColor(state.role, state.hero);
                roleChipDisc.color = state.alive ? color : Color.Lerp(color, Muted, 0.7f);
                roleChipIcon.sprite = state.alive ? RoleIcon(state.role, state.hero) : diedIcon;
                // The name only changes with the role or a death; the state arrives twice a second.
                if (state.role != chipRole || state.alive != chipAlive || state.hero != chipHero) {
                    chipRole = state.role;
                    chipAlive = state.alive;
                    chipHero = state.hero;
                    string name = MM_Text.RoleName(state.role, state.hero);
                    roleChipName.text = state.alive ? name : $"{name} <size=70%><color=#9AA3AF>· eliminated</color></size>";
                    roleChipName.color = Color.Lerp(color, Color.white, 0.2f);
                }
                coinChip.SetVisible(state.role != MM_Role.Spectator);
                SetCoinChip();
            }

            if (ShowOdds())
                SetOdds(oddsChip, state.murdererChance, state.sheriffChance);
            if (Classic && state.lifetimeCoins != skinChipCoins) {
                skinChipCoins = state.lifetimeCoins;
                skinChip.label.text = SkinLine(state.lifetimeCoins);
            }
        }

        void SetCoinChip() {
            bool full = state.coinCap > 0 && state.coins >= state.coinCap;
            coinChip.label.SetText("Bag {0}/{1}", (float)state.coins, (float)state.coinCap);
            coinChip.label.color = full ? Gold : Color.white;
        }

        bool ShowOdds() => Classic && state.phase == MM_Phase.Lobby && (state.murdererChance > 0 || state.sheriffChance > 0);

        static void SetOdds(HudChip chip, byte murderer, byte sheriff) {
            chip.label.text = $"Next round  <color=#F25050>Murderer {murderer}%</color>  <color=#5A99FF>Sheriff {sheriff}%</color>";
        }

        void FillResults() {
            MM_ResultsBroadcast r = lastResults;
            bool murdererWon = MM_Text.MurdererWon(r.outcome);
            Color color = murdererWon ? Alarm : MM_Text.RoleColor(MM_Role.Innocent);
            resultsTitle.text = (string.IsNullOrEmpty(r.headline) ? MM_Text.OutcomeHeadline(r.outcome) : r.headline).ToUpperInvariant();
            resultsTitle.color = Color.Lerp(color, Color.white, 0.2f);
            resultsDisc.color = color;
            resultsIcon.sprite = murdererWon ? murdererWinsIcon : innocentsWinIcon;
            resultsStripe.color = color;
            resultsSummary.text = r.summary;
            resultsCast.text = Cast(r);

            // This player's round.
            bool played = playedRound == r.round && playedRole is not (MM_Role.None or MM_Role.Spectator);
            resultsOutcome.SetVisible(played);
            resultsCoins.SetVisible(played);
            resultsXp.SetVisible(played);
            resultsStreak.SetVisible(played && (r.winStreak > 0 || r.bestWinStreak > 0));
            if (played) {
                resultsOutcome.label.text = r.youWon ? "Victory" : "Defeat";
                resultsOutcome.SetIcon(r.youWon ? victoryIcon : defeatIcon);
                resultsOutcome.SetTint(r.youWon ? Gold : Muted);
                resultsCoins.label.SetText("+{0} coins", r.yourCoins);
                resultsXp.label.SetText("+{0} XP", r.yourXp);
                resultsStreak.label.text = StreakLine(r.winStreak, r.bestWinStreak);
                resultsStreak.SetTint(r.winStreak > 1 ? Amber : Muted);
            }
            FillSkinProgress(r.lifetimeCoins);
            SetOdds(resultsOdds, r.murdererChance, r.sheriffChance);

            // Murderers, the sheriff, the hero and real players first; the crowd of NPC innocents last.
            var entries = new List<MM_ResultEntry>(r.entries ?? System.Array.Empty<MM_ResultEntry>());
            entries.Sort((a, b) => Rank(a).CompareTo(Rank(b)));
            int shown = Mathf.Min(entries.Count, maxResultRows);
            resultsRows.SetCount(shown);
            for (int i = 0; i < shown; i++) {
                MM_ResultEntry entry = entries[i];
                HudRow row = resultsRows.Row(i);
                Color roleColor = MM_Text.RoleColor(entry.role, entry.hero);
                row.SetIcon(RoleIcon(entry.role, entry.hero), roleColor);
                string who = !entry.isPlayer ? $"{entry.name} <size=80%><color=#7D8796>NPC</color></size>"
                    : string.IsNullOrEmpty(entry.username) ? entry.name
                    : $"{entry.name} <size=80%><color=#9AA3AF>@{entry.username}</color></size>";
                row.Set(0, who);
                row.Set(1, MM_Text.RoleName(entry.role, entry.hero), roleColor);
                row.Set(2, entry.survived ? "Survived" : "Died", entry.survived ? MM_Text.RoleColor(MM_Role.Innocent) : Muted);
                row.Set(3, entry.kills > 0 ? entry.kills.ToString() : "-", entry.kills > 0 ? Color.white : Muted);
                row.Set(4, entry.coins > 0 ? entry.coins.ToString() : "-", entry.coins > 0 ? Gold : Muted);
            }
            int hidden = entries.Count - shown;
            resultsMore.text = hidden > 0 ? $"+ {hidden} more townsfolk" : string.Empty;
            resultsMore.gameObject.SetActive(hidden > 0);
        }

        /// <summary>"Murderer Ada · Sheriff Bo · Hero Cy": who played the big parts.</summary>
        static string Cast(MM_ResultsBroadcast r) {
            var parts = new List<string>(3);
            if (!string.IsNullOrEmpty(r.murdererName))
                parts.Add($"<color=#F25050>Murderer</color> <b>{r.murdererName}</b>");
            if (!string.IsNullOrEmpty(r.sheriffName))
                parts.Add($"<color=#5A99FF>Sheriff</color> <b>{r.sheriffName}</b>");
            if (!string.IsNullOrEmpty(r.heroName))
                parts.Add($"<color=#FFC740>Hero</color> <b>{r.heroName}</b>");
            return string.Join("   ·   ", parts);
        }

        /// <summary>The long-term goal: lifetime coins towards the next knife skin.</summary>
        void FillSkinProgress(int lifetimeCoins) {
            MM_KnifeSkins.Skin current = MM_KnifeSkins.Get(MM_KnifeSkins.Unlocked(lifetimeCoins));
            int next = MM_KnifeSkins.Next(lifetimeCoins);
            skinBar.Value = next < 0 ? 1f : Mathf.InverseLerp(current.coins, MM_KnifeSkins.Get(next).coins, lifetimeCoins);
            skinBar.SetColor(next < 0 ? current.tint : MM_KnifeSkins.Get(next).tint);
            skinText.text = SkinLine(lifetimeCoins);
        }

        /// <summary>"Knife skin Rusty · 59 lifetime coins to Crimson".</summary>
        static string SkinLine(int lifetimeCoins) {
            MM_KnifeSkins.Skin current = MM_KnifeSkins.Get(MM_KnifeSkins.Unlocked(lifetimeCoins));
            int next = MM_KnifeSkins.Next(lifetimeCoins);
            if (next < 0)
                return $"Knife skin <b>{current.name}</b>  <color=#9AA3AF>· every skin unlocked</color>";
            MM_KnifeSkins.Skin upcoming = MM_KnifeSkins.Get(next);
            return $"Knife skin <b>{current.name}</b>  <color=#9AA3AF>· {upcoming.coins - lifetimeCoins} lifetime coins to</color> <b>{upcoming.name}</b>";
        }

        /// <summary>"3 wins in a row · new best!" / "Streak 0 · best 5".</summary>
        static string StreakLine(int streak, int best) {
            if (streak > 1 && streak >= best)
                return $"{streak} wins in a row · new best!";
            if (streak > 1)
                return $"{streak} wins in a row · best {best}";
            return streak == 1 ? $"1 win in a row · best {best}" : $"Streak lost · best {best}";
        }

        /// <summary>The sting for how the round went for you, and a cheer when the coins just unlocked a skin.</summary>
        void PlayResultsMoment() {
            MM_ResultsBroadcast r = lastResults;
            bool played = playedRound == r.round && playedRole is not (MM_Role.None or MM_Role.Spectator);
            if (played) {
                GameSfx.Play(r.youWon ? SfxCue.Win : SfxCue.Lose);
                LocalCharacter character = LocalPlayer.Character;
                if (r.youWon && winConfettiScale > 0f && character != null)
                    GameFx.Play(FxKind.Confetti, character.transform.position + Vector3.up * killFxHeight, winConfettiScale);
            }
            int before = MM_KnifeSkins.Unlocked(r.lifetimeCoins - r.yourCoins);
            int after = MM_KnifeSkins.Unlocked(r.lifetimeCoins);
            if (r.yourCoins > 0 && after > before) {
                MM_KnifeSkins.Skin skin = MM_KnifeSkins.Get(after);
                ScreenFx.ShowText($"NEW KNIFE SKIN: {skin.name.ToUpperInvariant()}", Color.Lerp(skin.tint, Color.white, 0.25f), newSkinTextSeconds);
                GameSfx.Play(SfxCue.Win);
            }
        }

        static int Rank(MM_ResultEntry entry) => entry.role switch {
            MM_Role.Murderer => 0,
            MM_Role.Sheriff => entry.hero ? 2 : 1,
            _ => entry.isPlayer ? 3 : entry.coins > 0 ? 4 : 5,
        };

        static Color WithAlpha(Color color, float alpha) => new(color.r, color.g, color.b, alpha);

